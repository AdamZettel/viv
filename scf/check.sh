# The Hartree-Fock checks, in two tiers.
#
#     scf/check.sh quick     the new library pages and the fast programs (under 5 min)
#     scf/check.sh full      every lib/hf module and every scf program
#     scf/check.sh lint      the lints, generated kernels and lenses only: the gate's
#                            scf check (its programs run in three engines there)
#
# Each program runs through tools/both-engines.sh: its tests must pass in the
# interpreter and in the native build, and the two outputs must agree line
# for line. Programs run in parallel (JOBS of them at once, default the CPU
# count); the report is one line per program, in a fixed order:
#
#     meta_scf                            9 tests pass, 0 failed; identical output
#
# tools/hf_names.sh (the name and library-rule lint) runs first and prints
# only when it finds something. `viv lint lib/hf lib/hfref` follows: no
# integer literal as an array size, a loop bound or an index bound
# (lang/viv/src/lint.rs, posts/README.md); a size comes from len/shape of
# the data, a limit from a named constant. Then `viv lens check` reads every lib/hf module that has an .intent file, which the
# SCF modules rhf, uhf, rohf and hf must have: a def whose body changed since
# its entry was stamped, a public def with no `what`, a long def with no
# steps, a step with no text, or a number in the prose with no test cited
# fails the check, in both tiers, and so does a drop in intent coverage
# (`viv lens coverage --check`, the ratchet in lens_coverage.json). The script exits nonzero on any failed
# test, any difference between the engines, any build failure, any lint
# finding or any lens problem.
#
#   quick: lib/hf/{integrals,hf,fuzz}, lib/hf/tests/{integrals,hf};
#          scf/{lock_water,meta_integrals,meta_scf,coverage}
#   full:  every lib/hf/*.viv and lib/hf/tests/*.viv; every scf/*.viv
#
# A module's tests that need reference data (lib/hfref) or the sweep drivers
# live in lib/hf/tests/<module>.viv, so that a program using the module does
# not load them; both tiers run them.
set -e
root=$(cd "$(dirname "$0")/.." && pwd)
tier=${1:-quick}
jobs=${JOBS:-$(sysctl -n hw.ncpu 2>/dev/null || nproc 2>/dev/null || echo 4)}

case "$tier" in
    quick)
        list="lib/hf:integrals lib/hf:hf lib/hf/tests:integrals lib/hf/tests:hf lib/hf:fuzz scf:meta_integrals scf:meta_scf scf:coverage scf:lock_water"
        ;;
    full)
        list=""
        for f in "$root"/lib/hf/*.viv; do list="$list lib/hf:$(basename "$f" .viv)"; done
        for f in "$root"/lib/hf/tests/*.viv; do list="$list lib/hf/tests:$(basename "$f" .viv)"; done
        for f in "$root"/scf/*.viv; do list="$list scf:$(basename "$f" .viv)"; done
        ;;
    lint)
        list=""
        ;;
    *)
        echo "usage: scf/check.sh quick|full|lint" >&2
        exit 2
        ;;
esac

if ! lint=$("$root/tools/hf_names.sh" 2>&1); then
    echo "$lint"
    exit 1
fi

# lib/hf/mdg_kernels is generated by lib/cas (tools/cas/gen_integrals.viv):
# it and its intent lens must be what the generator prints
if ! gen=$("$root/tools/cas/gen-integrals.sh" --check 2>&1); then
    echo "$gen"
    exit 1
fi

# no literal sizes (lang/viv/src/lint.rs)
if ! lint=$(cd "$root" && "$root/target/release/viv" lint lib/hf lib/hfref 2>&1); then
    echo "$lint"
    exit 1
fi


# The lenses. A module joins this list by getting an .intent file (`viv lens
# init lib/hf/<module>.viv`, then the words); the SCF modules may not leave it.
for m in rhf uhf rohf hf; do
    if [ ! -f "$root/lib/hf/$m.intent" ]; then
        echo "lib/hf/$m.intent is missing: the SCF modules are checked by their lenses"
        exit 1
    fi
done
lensed=$(cd "$root" && ls lib/hf/*.intent lib/hf/tests/*.intent | sed 's/\.intent$/.viv/')
if ! lens=$(cd "$root" && "$root/target/release/viv" lens check $lensed 2>&1); then
    echo "$lens" | grep -v ': ok$'
    exit 1
fi
# Intent coverage: no lib/hf or lib/basis
# module's share of explained defs, steps or glossary terms may fall below
# what lens_coverage.json records, and no stale entry, dead def or `serves`
# of nothing may appear.
if ! cov=$(cd "$root" && "$root/target/release/viv" lens coverage --check lib/hf lib/basis 2>&1 >/dev/null); then
    echo "$cov" | grep -v '^note:'
    exit 1
fi
# The architecture lens (lib/hf/layers.arch): no
# new layer violation and no budget over its limit growing, against
# arch_ratchet.json.
if ! arch=$(cd "$root" && "$root/target/release/viv" arch check --check lib/hf/layers.arch 2>&1 >/dev/null); then
    echo "$arch" | grep -v 'better than recorded'
    exit 1
fi

if [ "$tier" = lint ]; then
    echo "scf/check.sh lint: names, sizes, architecture, generated kernels, lenses and coverage hold"
    exit 0
fi

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# the slowest programs first, so the parallel run ends sooner
order=$(for item in $list; do echo "$item"; done | sort -t: -k2 | awk -F: '
    $2 ~ /^(lock_ccpvdz|lock_open|lock_breadth|meta_scf|meta_integrals|rys_eri|hgp_eri)$/ { print "0 " $0; next }
    { print "1 " $0 }' | sort -s -k1,1 | cut -d' ' -f2)
if [ "${GATE_CACHE:-}" = 1 ]; then
    # under the gate: a program whose inputs have not changed since it passed
    # is not run again (tools/gate/cache.py; its line says so)
    # shellcheck disable=SC2086
    python3 "$root/tools/gate/cache.py" items both-engines --outdir "$tmp" --jobs "$jobs" $order
else
    echo "$order" | xargs -P "$jobs" -n 1 sh -c '
        key=$(echo "$3" | tr "/:" "__")
        "$1/tools/both-engines.sh" "${3%%:*}" "${3#*:}" > "$2/$key.out" 2>&1
        echo $? > "$2/$key.rc"
        ' check "$root" "$tmp" || true
fi
# (in the "sh -c" script: $1 is the repo root, $2 the output directory, and
# $3 the dir:name item that xargs appends)

bad=0
for item in $list; do
    name=${item#*:}
    key=$(echo "$item" | tr "/:" "__")
    out="$tmp/$key.out"
    rc="$tmp/$key.rc"
    if [ ! -f "$rc" ] || [ "$(cat "$rc")" != 0 ]; then bad=1; fi
    # a test module's lines are named tests/<module>, apart from the module's own
    case "$item" in lib/hf/tests:*) pre="tests/" ;; *) pre="" ;; esac
    if [ -f "$out" ]; then sed "s|^|$pre|" "$out"; else printf '%-34s DID NOT RUN\n' "$pre$name"; bad=1; fi
done
exit $bad
