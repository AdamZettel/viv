"""Write www/src/lib/engines/hf-bases.json: Gaussian basis sets for the
Hartree-Fock engine, read from PySCF (the oracle lib/hf is locked against), so
that a molecule the engine builds from an XYZ file has exactly the shells and
primitives tools/hf_reference.py would give lib/hfref.

    python3 www/scripts/hf-tables.py

For each basis and element: the shells as PySCF stores them (angular momentum,
exponents, and the raw contraction coefficients of mol.bas_ctr_coeff, one
column per contraction). The engine's JavaScript splits general contractions
and drops zero coefficients the way tools/hf_reference.py's packs() does.

Also records PySCF's bohr (param.BOHR), which converts XYZ angstroms: using
PySCF's constant rather than CODATA's is what lets the engine reproduce
PySCF's energies to 1e-9 from the same angstrom geometry.
"""
import json, os
import pyscf
from pyscf import gto
from pyscf.data import nist

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
BASES = ['sto-3g', '6-31g', '6-31g*', 'cc-pvdz', 'def2-svp']
ELEMENTS = ['H', 'He', 'Li', 'Be', 'B', 'C', 'N', 'O', 'F', 'Ne', 'Na', 'Mg', 'Al', 'Si', 'P', 'S', 'Cl', 'Ar']

out = {'_': 'GENERATED by www/scripts/hf-tables.py from PySCF %s; do not edit' % pyscf.__version__,
       'pyscf': pyscf.__version__, 'bohr_angstrom': nist.BOHR, 'bases': {}}
for basis in BASES:
    table = {}
    for z, el in enumerate(ELEMENTS, start=1):
        try:
            mol = gto.M(atom=f'{el} 0 0 0', basis=basis, spin=z % 2, unit='Bohr', verbose=0)
        except Exception:
            continue      # PySCF has no such basis for this element
        shells = []
        for ib in range(mol.nbas):
            shells.append({'l': int(mol.bas_angular(ib)),
                           'exps': [float(x) for x in mol.bas_exp(ib)],
                           'coefs': [[float(c) for c in row] for row in mol.bas_ctr_coeff(ib).T]})
        table[el] = shells
    out['bases'][basis] = table
# Orbital energies for the engine's example molecules, for its tests: lib/hfref
# pins energies and densities but not orbital energies. Same settings as
# tools/hf_reference.py (conv_tol 1e-12, symmetry off).
from pyscf import scf
EXAMPLES = {
    'water 6-31g RHF': ('O 0 0 0; H 0 -0.757 0.587; H 0 0.757 0.587', '6-31g', 0, 0, 'RHF'),
    'OH 6-31g UHF': ('O 0 0 0; H 0 0 0.9697', '6-31g', 0, 1, 'UHF'),
}
out['orbitals'] = {}
for name, (atom, basis, charge, spin, method) in EXAMPLES.items():
    mol = gto.M(atom=atom, basis=basis, charge=charge, spin=spin, unit='Angstrom', symmetry=False, verbose=0)
    mf = scf.RHF(mol) if method == 'RHF' else scf.UHF(mol)
    mf.conv_tol = 1e-12
    mf.kernel()
    mo = mf.mo_energy
    out['orbitals'][name] = {'energy': float(mf.e_tot),
                             'alpha': [float(x) for x in (mo if method == 'RHF' else mo[0])],
                             'beta': None if method == 'RHF' else [float(x) for x in mo[1]]}

path = os.path.join(ROOT, 'www', 'src', 'lib', 'engines', 'hf-bases.json')
with open(path, 'w') as f:
    json.dump(out, f, separators=(',', ':'))
    f.write('\n')
print(f'wrote {os.path.relpath(path, ROOT)}: ' + ', '.join(f'{b} ({len(t)} elements)' for b, t in out['bases'].items()))
