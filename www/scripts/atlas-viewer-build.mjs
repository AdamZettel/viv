// atlas-viewer-build -- the script and the styles of the page `viv atlas`
// writes (lang/viv/src/atlas.rs). The compiler carries them (include_str!),
// so a release build writes the page with no www/ beside it:
//
//   lang/viv/atlas/viewer.js    src/atlas/main.jsx with React and the site's
//                               components/CodeMap.jsx and ZoomWalk.jsx and
//                               KaTeX, one minified script
//   lang/viv/atlas/viewer.css   styles/data-palette.css, src/atlas/atlas.css,
//                               the syntax token rules of
//                               styles/viv.css, styles/codemap.css,
//                               styles/zoomwalk.css and katex.min.css with
//                               its fonts as woff2 data: URIs
//
// Run it after changing CodeMap.jsx, ZoomWalk.jsx, lib/codemap.js,
// lib/zoomwalk.js, lib/explore.js, lib/highlight.js or the styles:
// `node www/scripts/atlas-viewer-build.mjs`. The page must open from
// file:// with no network, so lib/repo.js is replaced by a copy that links
// nowhere, and the script refuses to write a bundle that loads anything.
import { build } from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const WWW = dirname(dirname(fileURLToPath(import.meta.url)));
const OUT = join(dirname(WWW), 'lang/viv/atlas');
mkdirSync(OUT, { recursive: true });

// lib/repo.js, for a page that links nowhere
const offline = {
  name: 'offline-repo',
  setup(b) {
    b.onResolve({ filter: /lib\/repo\.js$/ }, () => ({ path: 'repo', namespace: 'offline' }));
    b.onLoad({ filter: /.*/, namespace: 'offline' }, () => ({
      contents: "export const GITHUB = ''; export const REPO_PUBLIC = false; export const repoLink = () => null; export const PUBLIC_SITE = true; export const SHOW_NUMBER_CHECKS = false;",
      loader: 'js',
    }));
  },
};

const r = await build({
  entryPoints: [join(WWW, 'src/atlas/main.jsx')],
  bundle: true,
  minify: true,
  format: 'iife',
  target: 'es2020',
  jsx: 'automatic',
  define: { 'process.env.NODE_ENV': '"production"', 'import.meta.env': '{}' },
  plugins: [offline],
  write: false,
  // React's license notices, kept at the end of the bundle
  legalComments: 'eof',
  banner: { js: '// SPDX-License-Identifier: MIT OR Apache-2.0\n// SPDX-FileCopyrightText: 2026 The Viv authors\n// Generated by www/scripts/atlas-viewer-build.mjs: do not edit. Contains React (MIT, Meta Platforms, Inc. and affiliates) and KaTeX (MIT, Copyright (c) 2013-2020 Khan Academy and other contributors).' },
  logLevel: 'warning',
});
// React's errors name the page that explains them; the name stays, as text
// with no scheme, so that the only URLs left in the file are the XML
// namespaces (www.w3.org), which name and load nothing
const js = r.outputFiles[0].text.replaceAll('https://react.dev/errors/', 'react.dev/errors/');
// what a page from file:// cannot do: start a worker or load a script or a
// stylesheet. (CodeMap's fetch stays in the bundle, on the path the page never
// takes: it hands the map in.)
for (const bad of ['new Worker', 'importScripts', '<script src', '<link']) {
  if (js.includes(bad)) {
    console.error(`atlas-viewer-build: the bundle contains ${bad}; the page must open with no network`);
    process.exit(1);
  }
}
// the token classes lib/highlight.js emits (`.tk-kw` ...), from the site's
// own stylesheet; their colors are atlas.css's --tk-* (the Viv side's)
const vivCss = readFileSync(join(WWW, 'src/styles/viv.css'), 'utf8');
const tokens = vivCss.split('\n').filter((l) => /^\.tk-[a-z]+[ ,{]/.test(l));
if (tokens.length < 10) {
  console.error(`atlas-viewer-build: found ${tokens.length} syntax token rules (.tk-*) in styles/viv.css; the code would be uncolored`);
  process.exit(1);
}
// KaTeX's stylesheet, each font as its woff2 alone, inline (every browser
// that runs the bundle reads woff2; the woff and ttf copies would only add
// size)
const KATEX = join(WWW, 'node_modules/katex/dist');
const katexVersion = JSON.parse(readFileSync(join(WWW, 'node_modules/katex/package.json'), 'utf8')).version;
let fonts = 0;
const katexCss = readFileSync(join(KATEX, 'katex.min.css'), 'utf8').replace(/src:([^;}]*)/g, (all, list) => {
  const woff2 = /url\((fonts\/[\w-]+\.woff2)\)/.exec(list);
  if (!woff2) {
    console.error(`atlas-viewer-build: a KaTeX font with no woff2: ${all.slice(0, 120)}`);
    process.exit(1);
  }
  fonts++;
  return `src:url(data:font/woff2;base64,${readFileSync(join(KATEX, woff2[1])).toString('base64')}) format("woff2")`;
});
if (fonts < 10) {
  console.error(`atlas-viewer-build: found ${fonts} KaTeX fonts in katex.min.css; the math would be set in the wrong faces`);
  process.exit(1);
}
const css = [
  // the data palette first (the walk's running def is data), the Viv side's
  // colors after it
  readFileSync(join(WWW, 'src/styles/data-palette.css'), 'utf8'),
  readFileSync(join(WWW, 'src/atlas/atlas.css'), 'utf8'),
  '/* the syntax tokens, from styles/viv.css */\n' + tokens.join('\n'),
  readFileSync(join(WWW, 'src/styles/codemap.css'), 'utf8'),
  readFileSync(join(WWW, 'src/styles/zoomwalk.css'), 'utf8'),
  `/* KaTeX ${katexVersion}, Copyright (c) 2013-2020 Khan Academy and other contributors, MIT license; its fonts inline as woff2 */\n${katexCss}`,
].join('\n');
// the only url( the styles may hold is a font written into them
if (/@import/.test(css) || /url\((?!data:font\/woff2;base64,)/.test(css)) {
  console.error('atlas-viewer-build: the styles load a file (url( or @import); the page must open with no network');
  process.exit(1);
}
// `</script` would end the <script> element the compiler puts the bundle
// in, and `</style` the <style>; `<\/script` is the same text in a string, a
// regular expression or a template
writeFileSync(join(OUT, 'viewer.js'), js.replace(/<\/script/gi, '<\\/script'));
writeFileSync(join(OUT, 'viewer.css'), css.replace(/<\/style/gi, ''));
console.log(`atlas-viewer-build: viewer.js ${(js.length / 1024).toFixed(0)} KB, viewer.css ${(css.length / 1024).toFixed(0)} KB in lang/viv/atlas`);
