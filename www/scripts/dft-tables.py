"""Write www/src/lib/engines/dft-tables.json: what the DFT engine's adapters
need from the Python side of dft/, read from there rather than retyped.

    python3 www/scripts/dft-tables.py

  gth        every GTH-PADE entry in CP2K's table (the copy PySCF ships),
             parsed by dft/pseudo/make_pseudo.py's own parse(): the adapters
             pick and print pseudopotentials exactly as make_pseudo.py does
  materials  dft/ref/materials.py's table: lattice constant, atoms with their
             GTH entries, cutoff, k-mesh, smearing and band count
  notes      make_deck.py's one-line description of each material
  nseg       make_deck.py's points per band-path segment

Needs numpy and PySCF, like make_deck.py. Rerun it when either table changes;
www/scripts/enginetest.mjs fails if the JSON and the Python disagree about
silicon or gallium arsenide, because it compares the decks they produce.
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(ROOT, 'dft', 'pseudo'))
sys.path.insert(0, os.path.join(ROOT, 'dft', 'ref'))
import make_pseudo
from materials import MATERIALS
import make_deck

tab = make_pseudo.entries(make_pseudo.table_path())
gth = {}
for (el, name), rows in sorted(tab.items()):
    zion, rloc, c, shells = make_pseudo.parse(rows)
    gth.setdefault(el, []).append({
        'name': f'{el} {name}',
        'q': int(name.split('q')[-1]),
        'zion': zion, 'rloc': rloc, 'cloc': c,
        'shells': [{'r': r, 'nprj': npr, 'h': h} for r, npr, h in shells],
    })

materials = {}
for name, (a, atoms, ecut, nk, smear, nb) in MATERIALS.items():
    materials[name] = {
        'alat': a, 'atoms': [{'entry': e, 'frac': list(map(float, f))} for e, f in atoms],
        'ecut': float(ecut), 'nkmesh': nk, 'smear': float(smear), 'nbands': nb,
    }

out = {
    '_': 'GENERATED by www/scripts/dft-tables.py from dft/pseudo/make_pseudo.py, dft/ref/materials.py and dft/ref/make_deck.py; do not edit',
    'nseg': make_deck.NSEG,
    'notes': make_deck.NOTES,
    'titles': make_deck.TITLES,
    'materials': materials,
    'gth': gth,
}
path = os.path.join(ROOT, 'www', 'src', 'lib', 'engines', 'dft-tables.json')
with open(path, 'w') as f:
    json.dump(out, f, indent=1)
    f.write('\n')
print(f'wrote {os.path.relpath(path, ROOT)}: {sum(len(v) for v in gth.values())} GTH entries for {len(gth)} elements, {len(materials)} materials')
