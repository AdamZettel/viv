// data-palette -- writes src/lib/dataPalette.mjs out as CSS custom properties
// (src/styles/data-palette.css: --data-1 .. --data-4, --data-text, --data-glow, --data-bg, --data-ink, --data-muted, --data-grid) and as a Rust table (lang/viv/src/data_palette.rs).
//     node scripts/data-palette.mjs           write both
//     node scripts/data-palette.mjs --check   fail if either is stale; also checks contrast
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { DATA_PALETTE as D } from '../src/lib/dataPalette.mjs';

const WWW = dirname(dirname(fileURLToPath(import.meta.url)));
const ROOT = dirname(WWW);
const lum = (hex) => {
  const c = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255).map((v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4));
  return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2];
};
const ratio = (a, b) => (Math.max(lum(a), lum(b)) + 0.05) / (Math.min(lum(a), lum(b)) + 0.05);
const BG = { light: D.light.bg, dark: D.dark.bg };
const problems = [];
for (const mode of ['light', 'dark']) {
  for (const c of D[mode].series) if (ratio(c, BG[mode]) < 3) problems.push(`${mode} ${c}: ${ratio(c, BG[mode]).toFixed(2)}:1 on ${BG[mode]}, under 3:1 for a stroke`);
  for (const c of [D[mode].text, D[mode].ink, D[mode].muted]) if (ratio(c, BG[mode]) < 4.5) problems.push(`${mode} ${c}: ${ratio(c, BG[mode]).toFixed(2)}:1 on ${BG[mode]}, under 4.5:1 for text`);
}

const vars = (m) => [...D[m].series.map((c, i) => `  --data-${i + 1}: ${c};`), ...['text', 'glow', 'bg', 'ink', 'muted', 'grid'].map((k) => `  --data-${k}: ${D[m][k]};`)].join('\n');
const css = `/* SPDX-License-Identifier: MIT OR Apache-2.0 */
/* SPDX-FileCopyrightText: 2026 The Viv authors */
/* GENERATED by scripts/data-palette.mjs from src/lib/dataPalette.mjs; do not edit.
   The data palette: series 1-4 are cyan, amber, indigo, green, the same on
   both sides; identity colors stay in viv.css. */
:root,
:root[data-theme='light'] {
${vars('light')}
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
${vars('dark').replace(/^/gm, '  ')}
  }
}
:root[data-theme='dark'] {
${vars('dark')}
}
`;
const rs = `// SPDX-License-Identifier: MIT OR Apache-2.0
// SPDX-FileCopyrightText: 2026 The Viv authors
// GENERATED by www/scripts/data-palette.mjs from www/src/lib/dataPalette.mjs; do not edit.
//! The data palette: the colors of data series, the same on both sides of the
//! site. Series order: cyan, amber, indigo, green.

/// Series colors on a light background (deeper shades, crisp strokes).
pub const DATA_LIGHT: [&str; ${D.light.series.length}] = [${D.light.series.map((c) => `"${c}"`).join(', ')}];
/// Series colors on a dark background (bright shades, drawn with a soft glow).
pub const DATA_DARK: [&str; ${D.dark.series.length}] = [${D.dark.series.map((c) => `"${c}"`).join(', ')}];
/// The glow around the primary series in dark mode; none in light mode.
pub const DATA_GLOW_DARK: &str = "${D.dark.glow}";
/// A figure's background, ink, muted text and grid: [light, dark].
pub const DATA_BG: [&str; 2] = ["${D.light.bg}", "${D.dark.bg}"];
pub const DATA_INK: [&str; 2] = ["${D.light.ink}", "${D.dark.ink}"];
pub const DATA_MUTED: [&str; 2] = ["${D.light.muted}", "${D.dark.muted}"];
pub const DATA_GRID: [&str; 2] = ["${D.light.grid}", "${D.dark.grid}"];
`;
const out = [[join(WWW, 'src/styles/data-palette.css'), css], [join(ROOT, 'lang/viv/src/data_palette.rs'), rs]];
if (process.argv.includes('--check')) {
  for (const [p, t] of out) if (!existsSync(p) || readFileSync(p, 'utf8') !== t) problems.push(`${p} is stale: run node scripts/data-palette.mjs`);
} else for (const [p, t] of out) writeFileSync(p, t);
if (problems.length) {
  console.error(`data-palette:\n  ${problems.join('\n  ')}`);
  process.exit(1);
}
console.log('data-palette: 4 series in both themes; strokes 3:1 or better, text 4.5:1 or better on the figure background');
