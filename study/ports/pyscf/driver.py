# what the verification hash covers besides viv/, upstream/ and oracle/
SOURCE_DIRS = ["lib/hf", "lib/basis", "lib/xyz.viv"] if os.path.isfile(os.path.join(REPO, "lib/xyz.viv")) else ["lib/hf", "lib/basis"]

BASIS_TABLE = {"sto-3g": "sto3g", "6-31g": "631g", "6-31g*": "631gs", "cc-pvdz": "ccpvdz", "cc-pvtz": "ccpvtz"}

STAGES = ["one_electron", "two_electron", "guess", "orthogonalize", "jk", "diis", "diagonalize", "energy", "other"]

# Viv's steps (def/step) -> the stage row. Exclusive times: a step's time
# excludes the steps inside it.
VIV_STAGE = {
    "integrals/one_electron": "one_electron",
    "integrals/two_electron": "two_electron",
    "ao_eri/compute": "two_electron",
    "ao_eri/transform": "two_electron",
    "scf/guess": "guess",
    "scf_iterate/orthonormal_basis": "orthogonalize",
    "scf_iterate/coulomb_exchange": "jk",
    "scf_iterate/commutator": "diis",
    "scf_iterate/diis": "diis",
    "scf_iterate/diagonalize": "diagonalize",
    "scf_iterate/energy": "energy",
}
# the steps whose sum is the run (PySCF's kernel() plus its integrals)
VIV_RUN_STEPS = ["scf_with/integrals", "scf_with/scf"]


def cases():
    return CONF["case"]


def case_conf(name):
    for c in CONF["case"]:
        if c["name"] == name:
            return c
    raise SystemExit(f"no case {name!r}")


def selected(ctx):
    want = [s for s in (ctx.args.cases.split(",") if ctx and ctx.args.cases else []) if s]
    return [c for c in cases() if not want or c["name"] in want]


def oracle(name):
    return json.load(open(os.path.join(HERE, "oracle", name + ".json")))


def lit(x):
    """A Viv literal that is the same double as the oracle's repr."""
    s = repr(float(x))
    if "e" in s:
        m, e = s.split("e")
        if "." not in m:
            m += ".0"
        s = m + "e" + e
    elif "." not in s and "inf" not in s and "nan" not in s:
        s += ".0"
    return s


def arr_lit(xs):
    return "[" + ", ".join(lit(x) for x in xs) + "]"


def title(c, o):
    return "%s %s, %s, %d AOs" % (c["method"].upper(), c["basis"], c["name"], o["nao"])


def header(c, o, purpose):
    v = CONF["verify"]
    t = CONF["timing"]
    lines = [
        "# %s: %s." % (purpose, title(c, o)),
        "# Generated by `python3 study/ports/harness/port.py gen pyscf` from",
        "# study/ports/pyscf/port.toml and oracle/%s.json. Do not edit." % c["name"],
        "#",
        "# PySCF %s: scf.%s(gto.M(atom, basis=%r, charge=%d, spin=%d)) with" % (o["pyscf"], c["method"].upper(), c["basis"], o["charge"], o["spin"]),
        "# init_guess \"1e\" and CDIIS over 8 Fock matrices from cycle 1.",
    ]
    if purpose == "verification":
        lines += [
            "# At conv_tol %g, conv_tol_grad %g: E = %s after %d cycles." % (v["pyscf_conv_tol"], v["pyscf_conv_tol_grad"], o["e_tot"], o["cycles"]),
            "# Viv: the same molecule and basis, the core guess (GS_CORE), CDIIS over 8",
            "# from the second iteration (diis_start 1, as PySCF's diis_start_cycle 1),",
            "# e_tol %g, grad_tol %g. Held to PySCF within %g Eh (energy) and %g Eh" % (v["viv_e_tol"], v["viv_grad_tol"], v["energy_tol"], v["mo_energy_tol"]),
            "# (orbital energies); the checks are steps of pz_check (viv/pzcheck.viv).",
        ]
    elif purpose == "timing":
        lines += [
            "# At conv_tol %g (conv_tol_grad sqrt(conv_tol)): E = %s after %d cycles." % (t["pyscf_conv_tol"], o["timing_e_tot"], o["timing_cycles"]),
            "# Viv: the core guess, CDIIS over 8 with diis_start 1, e_tol %g, grad_tol %g. The run must land within %g Eh of the" % (t["viv_e_tol"], t["viv_grad_tol"], t["timing_energy_tol"]),
            "# verification energy, or its time does not count.",
        ]
    else:
        lines += ["# The timing baseline: the molecule is built and nothing else runs."]
    return lines


def molecule_lines(c, o):
    lines = ['pz_mol0 = molecule("%s", "%s")' % (o["atom"], c["basis"])]
    if o["charge"] or o["spin"]:
        lines.append("pz_mol = Molecule { charge: %d, spin: %d, ..pz_mol0 }" % (o["charge"], o["spin"]))
    else:
        lines.append("pz_mol = pz_mol0")
    return lines


def options(c, e_tol, g_tol):
    method = "SCF_UHF" if c["method"] == "uhf" else "SCF_RHF"
    jk = "jk: INT_JK_DIRECT, " if c.get("jk") == "direct" else ""
    return "ScfOptions { method: %s, guess: GS_CORE, diis_start: 1, %se_tol: %s, grad_tol: %s, ..scf_defaults() }" % (method, jk, lit(e_tol), lit(g_tol))


def module_of_basis(key):
    """lib/basis's module for a table key: `pople631g` for the Pople sets (a
    module name cannot start with a digit; tools/basis_tables.py)."""
    return "pople" + key if key[0].isdigit() else key


def uses(c):
    return ["#! use lib/basis/%s" % module_of_basis(BASIS_TABLE[c["basis"]]), "#! use lib/hf/mole", "#! use lib/hf/scf", "#! use study/ports/pyscf/viv/pzcheck"]


def mo_refs(c, o):
    if c["method"] == "uhf":
        a, b = o["mo_energy_alpha"], o["mo_energy_beta"]
    else:
        a = b = o["mo_energy"]
    return [
        "#| PySCF's orbital energies, alpha then beta (hartree).",
        "def pz_mo_alpha() {",
        "    return " + arr_lit(a),
        "}",
        "def pz_mo_beta() {",
        "    return " + arr_lit(b),
        "}",
    ]


def program_verify(c, o):
    v = CONF["verify"]
    L = header(c, o, "verification") + uses(c) + [""]
    L += ["PZ_E = %s" % lit(o["e_tot"]), ""] + mo_refs(c, o) + [""]
    L += molecule_lines(c, o)
    L += ["pz_r = scf_with(pz_mol, %s)" % options(c, v["viv_e_tol"], v["viv_grad_tol"]),
          "pz_c = pz_check(pz_r, PZ_E, pz_mo_alpha(), pz_mo_beta())",
          "pz_print(pz_r, pz_c)", ""]
    L += ['test "%s: PySCF %s\'s energy %s within %g" {' % (c["name"], o["pyscf"], o["e_tot"], v["energy_tol"]),
          "    assert_near(pz_r.converged, 1.0, 0.0)",
          "    assert_lt(pz_c.energy_gap, %s)" % lit(v["energy_tol"]),
          "}", "",
          'test "%s: PySCF %s\'s orbital energies within %g" {' % (c["name"], o["pyscf"], v["mo_energy_tol"]),
          "    assert_lt(pz_c.mo_gap, %s)" % lit(v["mo_energy_tol"]),
          "}"]
    return "\n".join(L) + "\n"


def program_timing(c, o):
    t = CONF["timing"]
    L = header(c, o, "timing") + uses(c)[:3] + [""]
    L += ["PZ_E = %s" % lit(o["e_tot"]), ""]
    L += molecule_lines(c, o)
    L += ["pz_r = scf_with(pz_mol, %s)" % options(c, t["viv_e_tol"], t["viv_grad_tol"]),
          'print(f"energy {pz_r.energy:.17g}")',
          'print(f"iterations {pz_r.iterations:d}")', "",
          'test "%s, timing settings: within %g of PySCF\'s converged energy" {' % (c["name"], t["timing_energy_tol"]),
          "    assert_near(pz_r.converged, 1.0, 0.0)",
          "    assert_lt(abs(pz_r.energy - PZ_E), %s)" % lit(t["timing_energy_tol"]),
          "}"]
    return "\n".join(L) + "\n"


def program_baseline(c, o):
    L = header(c, o, "baseline") + uses(c)[:2] + [""]
    L += molecule_lines(c, o)
    L += ["print(mol_nao(pz_mol))", "",
          'test "%s: the molecule has PySCF\'s %d functions" {' % (c["name"], o["nao"]),
          "    assert_near(mol_nao(pz_mol), %d, 0.0)" % o["nao"],
          "}"]
    return "\n".join(L) + "\n"


def generated():
    out = {}
    for c in cases():
        o = oracle(c["name"])
        for fn, text in ((c["name"] + ".viv", program_verify(c, o)), (c["name"] + "_t.viv", program_timing(c, o)), (c["name"] + "_0.viv", program_baseline(c, o))):
            out[fn] = migrated(text, os.path.join(VIVDIR, fn))
    return out


def gen(ctx=None, check=False):
    stale = []
    for fn, text in generated().items():
        p = os.path.join(VIVDIR, fn)
        if check:
            if not os.path.exists(p) or open(p).read() != text:
                stale.append(fn)
        else:
            open(p, "w").write(text)
    if check and stale:
        raise SystemExit("out of date (run port.py gen pyscf): " + ", ".join(stale))
    if not check:
        print("wrote %d programs to %s" % (len(generated()), os.path.relpath(VIVDIR, REPO)))


# ---- native verification (check.sh) -----------------------------------------------------

def parse_out(text):
    vals = {}
    for line in text.splitlines():
        parts = line.split()
        if len(parts) == 2 and parts[0] in ("energy", "iterations", "converged", "energy_gap", "mo_gap"):
            vals[parts[0]] = float(parts[1])
    vals["pass"] = sum(1 for l in text.splitlines() if l.startswith("PASS "))
    vals["fail"] = sum(1 for l in text.splitlines() if l.startswith("FAIL ") or l.startswith("error"))
    return vals


def native_one(c, outdir):
    name = c["name"]
    src = os.path.join(VIVDIR, name + ".viv")
    exe = os.path.join(outdir, name)
    viv = os.environ.get("VIV", os.path.join(REPO, "target", "release", "viv"))
    # the exact build, the modules' objects from viv's object cache
    # two compilers per case, since the
    # cases run in parallel
    env = dict(os.environ, VIV_JOBS=os.environ.get("VIV_JOBS", "2"))
    r = subprocess.run([viv, "build", src, "-o", exe], cwd=REPO, capture_output=True, text=True, env=env)
    if r.returncode:
        return name, None, "viv build: " + (r.stdout + r.stderr)[:400]
    t0 = _time.perf_counter()
    r = subprocess.run([exe], capture_output=True, text=True)
    wall = _time.perf_counter() - t0
    v = parse_out(r.stdout + r.stderr)
    v["wall"] = wall
    return name, v, None


def native(jobs=None):
    """Every case natively at the verification settings: its tests pass, and
    its printed energy agrees with the oracle within energy_tol (checked here
    a second time, from the JSON, not from the literal in the program)."""
    import tempfile
    vt = CONF["verify"]
    outdir = tempfile.mkdtemp(prefix="p0native")
    jobs = jobs or int(os.environ.get("JOBS", "4"))
    bad = 0
    rows = {}
    order = sorted(cases(), key=lambda c: -oracle(c["name"])["nao"])
    with concurrent.futures.ThreadPoolExecutor(max_workers=jobs) as ex:
        for name, v, err in ex.map(lambda c: native_one(c, outdir), order):
            rows[name] = (v, err)
    table = []
    for c in cases():
        name = c["name"]
        v, err = rows[name]
        if err:
            print("%-24s FAILED TO BUILD: %s" % (name, err))
            bad = 1
            continue
        o = oracle(name)
        de = abs(v.get("energy", float("nan")) - float(o["e_tot"]))
        ok = v["fail"] == 0 and v["pass"] >= 2 and de < vt["energy_tol"] and v.get("converged") == 1
        bad |= not ok
        print("%-24s %3d AOs  E %.12f  |dE| %.1e  |d eps| %.1e  iterations %2d (PySCF %2d cycles)  %d tests pass, %d failed  %.1f s%s" % (
            name, o["nao"], v.get("energy", float("nan")), de, v.get("mo_gap", float("nan")), v.get("iterations", -1), o["cycles"], v["pass"], v["fail"], v["wall"], "" if ok else "  FAIL"))
        table.append({"case": name, "nao": o["nao"], "method": c["method"], "basis": c["basis"],
                      "pyscf_e": o["e_tot"], "viv_e": repr(v.get("energy")), "abs_de": de, "mo_gap": v.get("mo_gap"),
                      "viv_iterations": v.get("iterations"), "pyscf_cycles": o["cycles"]})
    os.makedirs(os.path.join(HERE, "results"), exist_ok=True)
    import portkit
    portkit.save_json(os.path.join(HERE, "results", "verify.json"), {"rows": table, "settings": CONF["verify"]})
    return bad


# ---- timing ------------------------------------------------------------------------------

def viv_stages(st):
    """Stage rows from a __stagetime__ record; `run` is the scf_with steps."""
    rows = {s: 0.0 for s in STAGES}
    run = sum(st.get(k, [0.0, 0, 0.0])[2] for k in VIV_RUN_STEPS)
    for k, (t, n, ti) in st.items():
        if k in VIV_STAGE:
            rows[VIV_STAGE[k]] += t
    rows["other"] = run - sum(rows[s] for s in STAGES if s != "other")
    return run, rows


def pyscf_stages(rec):
    rows = {s: 0.0 for s in STAGES}
    for k, t in rec["stages"].items():
        rows[k if k in rows else "other"] += t
    return rec["total"], rows


def median_rows(recs):
    keys = recs[0].keys()
    return {k: statistics.median(r[k] for r in recs) for k in keys}


def time(ctx):
    import port
    import portkit
    t = CONF["timing"]
    limit = t["load_limit"]
    want_engines = [e for e in ctx.args.engines.split(",") if e] if ctx.args.engines else None
    out_path = os.path.join(ctx.results, "final.json" if ctx.args.final else "provisional.json")
    prev = json.load(open(out_path)) if os.path.exists(out_path) else {"cases": {}}
    prev["versions"] = portkit.versions()
    prev["versions"]["pyscf"] = oracle(cases()[0]["name"])["pyscf"]
    import time as clock
    deadline = clock.time() + ctx.args.max_wait
    todo = list(selected(ctx))
    attempts = {}
    while todo:
        c = todo.pop(0)
        name = c["name"]
        if ctx.args.final:
            quiet, la = port.wait_quiet(limit, max(0, deadline - clock.time()))
            if not quiet:
                print(f"{name}: load {la:.2f} still at or above {limit} after waiting; stopping")
                break
        o = oracle(name)
        engines = want_engines or (["original"] + c["engines"])
        rec = prev["cases"].get(name, {})
        rec.update({"nao": o["nao"], "method": c["method"], "basis": c["basis"], "pyscf_cycles": o["timing_cycles"]})
        print(f"== {name} ({o['nao']} AOs)", flush=True)
        if "original" in engines:
            rec["pyscf"] = time_pyscf(name, o, t)
            show(name, "pyscf", rec["pyscf"])
            if c.get("jk") == "direct":
                rec["pyscf_incore"] = time_pyscf(name, o, t, ["--incore"])
                show(name, "pyscf_ic", rec["pyscf_incore"])
            rec["pyscf_chk"] = time_pyscf(name, o, t, ["--chk"])
            show(name, "pyscf_chk", rec["pyscf_chk"])
            rec["pyscf_cold"] = cold_pyscf(name, t, min(t["reps_cold"], case_reps(name, t)))
        info = None
        viv_engines = [e for e in engines if e != "original"]
        if viv_engines:
            info = port.build_viv_timed(os.path.join(VIVDIR, name + "_t.viv"), os.path.join(ctx.build, name), wasm="wasm" in viv_engines)
            base = port.build_viv_timed(os.path.join(VIVDIR, name + "_0.viv"), os.path.join(ctx.build, name + "_0"), wasm="wasm" in viv_engines)
            rec["compile"] = {k: info.get(k) for k in ("viv_to_c_s", "cc_s", "cc_release_s", "cc_fast_s", "viv_to_wasm_s")}
        for e in viv_engines:
            if e in ("native", "release", "fast"):
                rec[e] = time_viv_native(info, e, o, t)
            elif e == "wasm":
                rec[e] = time_viv_process(info, base, "wasm", o, t)
            elif e == "interp":
                rec[e] = time_viv_process(info, base, "interp", o, t, reps=1)
            show(name, e, rec[e])
        if info:
            rec["native_cold"] = {"compile": info["viv_to_c_s"] + info["cc_s"],
                                  "run_process": rec.get("native", {}).get("process_median"),
                                  "total": info["viv_to_c_s"] + info["cc_s"] + (rec.get("native", {}).get("process_median") or 0.0)}
        prev["cases"][name] = rec
        prev["taken"] = time_now()
        portkit.save_json(out_path, prev)
        if ctx.args.final:
            worst = max((v.get("load_max", 0) for v in rec.values() if isinstance(v, dict)), default=0)
            attempts[name] = attempts.get(name, 0) + 1
            if worst >= limit and attempts[name] < 3 and clock.time() < deadline:
                print(f"{name}: a run saw load {worst:.2f}; timing it again after the queue", flush=True)
                todo.append(c)
    print("wrote", os.path.relpath(out_path, REPO))


def time_now():
    import time as _t
    return _t.strftime("%Y-%m-%dT%H:%M:%S")


def show(name, eng, r):
    if not r or "total" not in r:
        print(f"   {eng:8s} {r}")
        return
    star = "" if r.get("load_max", 0) < CONF["timing"]["load_limit"] else " *"
    st = r.get("stages", {})
    parts = " ".join(f"{k}={v*1e3:.1f}" for k, v in st.items() if v)
    print(f"   {eng:8s} total {r['total']*1e3:9.1f} ms{star}  (load max {r.get('load_max', 0):.2f})  {parts}", flush=True)


def case_reps(name, t):
    return case_conf(name).get("reps", t["reps_warm"])


def time_pyscf(name, o, t, extra=()):
    import port
    reps = case_reps(name, t)
    r = port.run_timed_capture([PY, "-W", "ignore", os.path.join(HERE, "pyscf_side.py"), "time", name, str(reps)] + list(extra), REPO)
    recs = [json.loads(l) for l in r["stdout"].splitlines() if l.startswith("{")]
    warm = [x for x in recs if not x["warmup"]]
    if not warm or not all(x["ok"] for x in recs):
        return {"error": "PySCF run did not match the oracle", "raw": recs, "stderr": r["stderr"][-2000:]}
    totals, rows = zip(*(pyscf_stages(x) for x in warm))
    return {"total": statistics.median(totals), "totals": list(totals), "stages": median_rows(list(rows)),
            "cycles": warm[0]["cycles"], "cpu_over_wall": max(x["cpu_over_wall"] for x in warm),
            "calls": warm[0]["calls"], "load_start": r["load_start"], "load_max": r["load_max"]}


def cold_pyscf(name, t, reps):
    import port
    walls = []
    lmax = 0.0
    for _ in range(reps):
        r = port.run_timed([PY, "-W", "ignore", os.path.join(HERE, "pyscf_side.py"), "cold", name], REPO)
        walls.append(r["wall"])
        lmax = max(lmax, r["load_max"])
    return {"total": statistics.median(walls), "all": walls, "load_max": lmax}


def check_energy(stdout, o, t):
    v = parse_out(stdout)
    return v, ("energy" in v and abs(v["energy"] - float(o["e_tot"])) < t["timing_energy_tol"] and v["fail"] == 0)


def time_viv_native(info, eng, o, t):
    import port
    exe = {"native": info["exe"], "release": info["exe_release"], "fast": info.get("exe_fast")}[eng]
    reps = case_reps(info["name"][:-2], t)
    # a short program's first process warms the page cache and is not
    # counted; a long one (reps set in port.toml) runs once
    first = 0 if reps < t["reps_warm"] else 1
    runs, procs, lmax, lstart, iters = [], [], 0.0, None, None
    for i in range(reps + first):
        r = port.run_timed_capture([exe], os.path.dirname(exe))
        v, ok = check_energy(r["stdout"], o, t)
        if not ok:
            return {"error": "energy does not match the oracle", "stdout": r["stdout"][-600:], "stderr": r["stderr"][-600:]}
        st = port.parse_stagetime(r["stderr"])
        lstart = r["load_start"] if lstart is None else lstart
        if i < first:
            continue
        lmax = max(lmax, r["load_max"])
        run, rows = viv_stages(st)
        runs.append((run, rows, st))
        procs.append(r["wall"])
        iters = v.get("iterations")
    totals = [x[0] for x in runs]
    return {"total": statistics.median(totals), "totals": totals, "stages": median_rows([x[1] for x in runs]),
            "steps": {k: statistics.median(x[2][k][0] for x in runs) for k in runs[0][2]},
            "step_counts": {k: runs[0][2][k][1] for k in runs[0][2]},
            "process_median": statistics.median(procs), "iterations": iters,
            "load_start": lstart, "load_max": lmax}


def time_viv_process(info, base, eng, o, t, reps=None):
    """wasm and interpreter: no stage clocks; the run is the process time of
    the timing program minus that of the baseline (the molecule only)."""
    import port
    import portkit
    reps = reps or min(t["reps_cold"], case_reps(info["name"][:-2], t))
    full, zero, lmax, iters = [], [], 0.0, None
    for i in range(reps):
        for which, inf, acc in (("t", info, full), ("0", base, zero)):
            if eng == "wasm":
                if not inf.get("wasm"):
                    return {"error": "no wasm build: " + inf.get("wasm_error", "")}
                cmd = [portkit.NODE, portkit.RUN_WASM, inf["wasm"]]
            else:
                cmd = [port.VIV, "run", "--quiet", inf["src"]]
            r = port.run_timed_capture(cmd, REPO, timeout=3600)
            if which == "t":
                v, ok = check_energy(r["stdout"], o, t)
                if not ok:
                    return {"error": "energy does not match the oracle", "stdout": r["stdout"][-600:], "stderr": r["stderr"][-600:]}
                iters = v.get("iterations")
            acc.append(r["wall"])
            lmax = max(lmax, r["load_max"])
    return {"total": statistics.median(full) - statistics.median(zero), "process": full, "baseline": zero,
            "iterations": iters, "load_max": lmax}


