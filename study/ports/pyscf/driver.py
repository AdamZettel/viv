def parse_sample(path):
    """{symbol: samples} from `sample`'s "Sort by top of stack" table."""
    counts = {}
    on = False
    for line in open(path, errors="replace"):
        if line.startswith("Sort by top of stack"):
            on = True
            continue
        if on:
            if not line.strip():
                if counts:
                    break
                continue
            if line.startswith("Binary Images"):
                break
            parts = line.strip().rsplit(None, 1)
            if len(parts) == 2 and parts[1].isdigit():
                sym = parts[0].split("  (in ")[0].strip()
                counts[sym] = counts.get(sym, 0) + int(parts[1])
    return counts


def classify_samples(counts):
    sys.path.insert(0, HERE)
    import lines as L
    defs = L.viv_defs()
    groups = {}
    for sym, n in counts.items():
        # process start (dyld) and the sampler's own mach calls are not the program
        if sym.startswith("_dyld") or sym.startswith("dyld") or sym.startswith("mach_msg"):
            continue
        g = None
        if sym in defs:
            g = SAMPLE_FILES.get(defs[sym][0], "SCF driver and the rest of lib/hf")
        else:
            for key, name in SAMPLE_RUNTIME:
                if key in sym:
                    g = name
                    break
        groups[g or "other runtime"] = groups.get(g or "other runtime", 0) + n
    total = sum(groups.values())
    return {k: v / total for k, v in sorted(groups.items(), key=lambda x: -x[1])}, total


