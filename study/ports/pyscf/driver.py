def sample_viv(exe, out):
    """macOS `sample` on the native binary at 1 ms for its whole run."""
    p = subprocess.Popen([exe], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, env=_env(), cwd=os.path.dirname(exe))
    subprocess.run(["sample", str(p.pid), "3600", "1", "-mayDie", "-file", out], capture_output=True, text=True)
    p.wait()
    scrub(out)
    return out


def scrub(path):
    """No local path in a committed file: the repository becomes <repo>, the
    home directory ~."""
    t = open(path, errors="replace").read()
    t = t.replace(REPO, "<repo>").replace(os.path.expanduser("~"), "~")
    open(path, "w").write(t)


