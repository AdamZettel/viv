"""Port P0's driver for study/ports/harness/port.py: lib/hf against PySCF 2.5.0.

    port.py gen pyscf        write viv/<case>.viv (verification), viv/<case>_t.viv
                             (timing) and viv/<case>_0.viv (the timing baseline:
                             the molecule only) from port.toml and oracle/
    python3 driver.py gen --check     fail if a generated program is out of date
    python3 driver.py native          build and run every verification program
                                      natively, compare with the oracle (check.sh)
    port.py time pyscf [--final]      the timing table (results/)
    port.py profile pyscf             cProfile of PySCF, `sample` of Viv native
    port.py report pyscf              results/RESULTS.md from final.json and
                                      provisional.json

Stages (one row each, the same rows for both sides; NOTES.md says what each
side's row contains):

    one_electron, two_electron, guess, orthogonalize, jk, diis, diagonalize,
    energy, other
"""
