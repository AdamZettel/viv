REPO = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
sys.path.insert(0, os.path.join(REPO, "study", "ports", "harness"))
CONF = tomllib.load(open(os.path.join(HERE, "port.toml"), "rb"))
