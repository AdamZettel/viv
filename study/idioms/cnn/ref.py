"""Reference for the Viv CNN port.

The model and loop follow pytorch/examples mnist/main.py (conv, relu, conv,
relu, max_pool2d, dropout, flatten, fc, relu, dropout, fc, log_softmax,
nll_loss, StepLR) at a size that fits 8x8 digits, trained with Adam in float64.

Two things the Viv program cannot get from torch are made explicit here so
both sides see the same numbers:
  - the per-epoch shuffle is torch.randperm, exported as ORDER;
  - the dropout masks come from Park-Miller MINSTD (Viv's rand()), because
    torch's dropout RNG is not reproducible outside torch.

Writes digits.viv (data, initial weights, epoch orders, reference results)
and prints the per-step losses and the per-epoch test numbers.
"""
import sys
import numpy as np
import torch
import torch.nn as nn
import torch.nn.functional as F
from sklearn.datasets import load_digits

torch.set_default_dtype(torch.float64)
N_TRAIN, N_TEST, BATCH, EPOCHS = 1024, 512, 32, 6
LR, GAMMA, P1, P2, SEED = 0.02, 0.7, 0.25, 0.5, 7.0
C1, C2, HIDDEN, CLASSES = 8, 16, 32, 10
FLAT = C2 * 2 * 2


class MinStd:
    """Viv's rand(): srand(s) sets state = s mod (2^31 - 2) + 1."""

    def __init__(self, seed):
        self.state = float(int(abs(seed) % 2147483646.0)) + 1.0

    def rand(self):
        self.state = (16807.0 * self.state) % 2147483647.0
        return self.state / 2147483647.0


class Net(nn.Module):
    def __init__(self):
        super().__init__()
        self.conv1 = nn.Conv2d(1, C1, 3, 1)
        self.conv2 = nn.Conv2d(C1, C2, 3, 1)
        self.fc1 = nn.Linear(FLAT, HIDDEN)
        self.fc2 = nn.Linear(HIDDEN, CLASSES)

    def forward(self, x, m1=None, m2=None):
        x = F.relu(self.conv1(x))
        x = F.relu(self.conv2(x))
        x = F.max_pool2d(x, 2)
        x = torch.flatten(x, 1)
        if m1 is not None:
            x = x * m1 / (1 - P1)
        x = F.relu(self.fc1(x))
        if m2 is not None:
            x = x * m2 / (1 - P2)
        return F.log_softmax(self.fc2(x), dim=1)


def masks(rng, b):
    m1 = [[1.0 if rng.rand() >= P1 else 0.0 for _ in range(FLAT)] for _ in range(b)]
    m2 = [[1.0 if rng.rand() >= P2 else 0.0 for _ in range(HIDDEN)] for _ in range(b)]
    return torch.tensor(m1), torch.tensor(m2)


def fmt_matrix(name, a):
    a = np.asarray(a, dtype=np.float64).reshape(len(a), -1)
    rows = ",\n     ".join("[" + ", ".join(repr(float(v)) for v in r) + "]" for r in a)
    return f"{name} = [{rows}]\n"


def fmt_vector(name, v):
    return f"{name} = [" + ", ".join(repr(float(x)) for x in np.ravel(v)) + "]\n"


def main():
    digits = load_digits()
    X = torch.tensor(digits.data[: N_TRAIN + N_TEST] / 16.0).reshape(-1, 1, 8, 8)
    y = torch.tensor(digits.target[: N_TRAIN + N_TEST], dtype=torch.long)
    Xtr, ytr, Xte, yte = X[:N_TRAIN], y[:N_TRAIN], X[N_TRAIN:], y[N_TRAIN:]

    torch.manual_seed(1)
    model = Net()
    init = {k: v.detach().clone() for k, v in model.state_dict().items()}
    opt = torch.optim.Adam(model.parameters(), lr=LR)
    sched = torch.optim.lr_scheduler.StepLR(opt, step_size=1, gamma=GAMMA)
    gen = torch.Generator().manual_seed(1)
    rng = MinStd(SEED)

    orders, losses, test_loss, test_correct = [], [], [], []
    for epoch in range(EPOCHS):
        model.train()
        order = torch.randperm(N_TRAIN, generator=gen)
        orders.append(order.numpy().astype(float))
        for start in range(0, N_TRAIN, BATCH):
            idx = order[start : start + BATCH]
            m1, m2 = masks(rng, len(idx))
            opt.zero_grad()
            loss = F.nll_loss(model(Xtr[idx], m1, m2), ytr[idx])
            loss.backward()
            opt.step()
            losses.append(loss.item())
            print(f"epoch {epoch} step {start // BATCH:2d} loss {loss.item():.15e}")
        sched.step()
        model.eval()
        with torch.no_grad():
            out = model(Xte)
            tl = F.nll_loss(out, yte, reduction="sum").item() / N_TEST
            correct = int((out.argmax(1) == yte).sum())
        test_loss.append(tl)
        test_correct.append(correct)
        print(f"epoch {epoch} test loss {tl:.15e} correct {correct}/{N_TEST}")

    final = torch.cat([p.detach().reshape(-1) for p in model.parameters()])
    print(f"final parameter sum {final.sum().item():.15e} |theta|^2 {(final**2).sum().item():.15e}")

    with open("digits.viv", "w") as f:
        f.write("# GENERATED by ref.py; do not edit.\n")
        f.write("# sklearn load_digits: first N_TRAIN images train, next N_TEST test, pixels / 16.\n")
        f.write("# Initial weights from torch.manual_seed(1); ORDER from torch.randperm.\n")
        f.write(f"N_TRAIN = {N_TRAIN}\nN_TEST = {N_TEST}\nBATCH = {BATCH}\nEPOCHS = {EPOCHS}\n")
        f.write(f"C1 = {C1}\nC2 = {C2}\nHIDDEN = {HIDDEN}\nCLASSES = {CLASSES}\n")
        f.write(f"LR = {LR}\nGAMMA = {GAMMA}\nP1 = {P1}\nP2 = {P2}\nSEED = {SEED}\n")
        f.write(fmt_matrix("X_TRAIN", Xtr.reshape(N_TRAIN, 64)))
        f.write(fmt_vector("Y_TRAIN", ytr))
        f.write(fmt_matrix("X_TEST", Xte.reshape(N_TEST, 64)))
        f.write(fmt_vector("Y_TEST", yte))
        f.write(fmt_matrix("ORDER", np.stack(orders)))
        # conv weights (O, C, 3, 3) as O rows of C*9, the layout torch's view(O, -1) gives
        f.write(fmt_matrix("INIT_CONV1", init["conv1.weight"].reshape(C1, 9)))
        f.write(fmt_matrix("INIT_BIAS1", init["conv1.bias"].reshape(1, -1)))
        f.write(fmt_matrix("INIT_CONV2", init["conv2.weight"].reshape(C2, C1 * 9)))
        f.write(fmt_matrix("INIT_BIAS2", init["conv2.bias"].reshape(1, -1)))
        f.write(fmt_matrix("INIT_FC1", init["fc1.weight"]))
        f.write(fmt_matrix("INIT_FC1_BIAS", init["fc1.bias"].reshape(1, -1)))
        f.write(fmt_matrix("INIT_FC2", init["fc2.weight"]))
        f.write(fmt_matrix("INIT_FC2_BIAS", init["fc2.bias"].reshape(1, -1)))
        f.write(fmt_vector("REF_LOSS", losses))
        f.write(fmt_vector("REF_TEST_LOSS", test_loss))
        f.write(fmt_vector("REF_TEST_CORRECT", test_correct))
        f.write(fmt_vector("REF_FINAL", final))


if __name__ == "__main__":
    sys.exit(main())
