"""Run karpathy/micrograd (the cloned original, unmodified) on the demo's moons
problem and write what the Viv port needs as a Viv source file, moons.viv:
the data, the initial parameters, and the reference loss/accuracy per step.

    python3 ref.py [N HIDDEN STEPS]        defaults: 100 16 100 (the demo's sizes)

Also runs micrograd's two engine tests against torch and writes their numbers.
"""
import os, random, sys
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "..", "..", "..", "src", "micrograd")
sys.path.insert(0, os.path.abspath(SRC))
from micrograd.engine import Value
from micrograd.nn import MLP
from sklearn.datasets import make_moons
import torch

N, HID, STEPS = (int(a) for a in sys.argv[1:4]) if len(sys.argv) > 3 else (100, 16, 100)

# --- the demo, cell for cell ---
np.random.seed(1337)
random.seed(1337)
X, y = make_moons(n_samples=N, noise=0.1)
y = y * 2 - 1
model = MLP(2, [HID, HID, 1])
P0 = [p.data for p in model.parameters()]


def loss():
    inputs = [list(map(Value, xrow)) for xrow in X]
    scores = list(map(model, inputs))
    losses = [(1 + -yi * scorei).relu() for yi, scorei in zip(y, scores)]
    data_loss = sum(losses) * (1.0 / len(losses))
    alpha = 1e-4
    reg_loss = alpha * sum((p * p for p in model.parameters()))
    total_loss = data_loss + reg_loss
    accuracy = [(yi > 0) == (scorei.data > 0) for yi, scorei in zip(y, scores)]
    return total_loss, sum(accuracy) / len(accuracy)


losses, accs = [], []
for k in range(STEPS):
    total_loss, acc = loss()
    model.zero_grad()
    total_loss.backward()
    if k == 0:
        G0 = [p.grad for p in model.parameters()]
    learning_rate = 1.0 - 0.9 * k / 100
    for p in model.parameters():
        p.data -= learning_rate * p.grad
    losses.append(total_loss.data)
    accs.append(acc)
    print(f"step {k} loss {total_loss.data:g} accuracy {acc*100:g}")
PF = [p.data for p in model.parameters()]

# --- micrograd's test/test_engine.py, both graphs, through torch ---
def sanity():
    x = torch.Tensor([-4.0]).double(); x.requires_grad = True
    z = 2 * x + 2 + x
    q = z.relu() + z * x
    h = (z * z).relu()
    yy = h + q + q * x
    yy.backward()
    return yy.item(), x.grad.item()


def more_ops():
    a = torch.Tensor([-4.0]).double(); b = torch.Tensor([2.0]).double()
    a.requires_grad = True; b.requires_grad = True
    c = a + b
    d = a * b + b**3
    c = c + c + 1
    c = c + 1 + c + (-a)
    d = d + d * 2 + (b + a).relu()
    d = d + 3 * d + (b - a).relu()
    e = c - d
    f = e**2
    g = f / 2.0
    g = g + 10.0 / f
    g.backward()
    return g.item(), a.grad.item(), b.grad.item()


s_y, s_dx = sanity()
m_g, m_da, m_db = more_ops()


def arr(v):
    return "[" + ", ".join(repr(float(t)) for t in v) + "]"


with open(os.path.join(HERE, "moons.viv"), "w") as f:
    f.write("# GENERATED by ref.py from karpathy/micrograd; do not edit.\n")
    f.write(f"# make_moons(n_samples={N}, noise=0.1), seeds 1337, MLP(2, [{HID}, {HID}, 1]).\n")
    f.write(f"N = {N}\nHIDDEN = {HID}\nSTEPS = {STEPS}\n")
    f.write("X = [" + ",\n     ".join(arr(r) for r in X) + "]\n")
    f.write(f"Y = {arr(y)}\n")
    f.write(f"P0 = {arr(P0)}\n")
    f.write(f"REF_GRAD0 = {arr(G0)}\n")
    f.write(f"REF_PFINAL = {arr(PF)}\n")
    f.write(f"REF_LOSS = {arr(losses)}\n")
    f.write(f"REF_ACC = {arr(accs)}\n")
    f.write(f"TORCH_SANITY = [{s_y!r}, {s_dx!r}]\n")
    f.write(f"TORCH_MORE = [{m_g!r}, {m_da!r}, {m_db!r}]\n")
