"""Write names_subset.viv: the first NW lines of makemore's names.txt, as a Viv
module holding the raw file text.

Viv has no file input: a string literal becomes data only through
`chars("...")`, so the file has to be pasted into source by a tool first.
This script is that tool (compare lib/corpus.viv and tools/make_corpus.mjs).

    python3 gen_names.py [NW]
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "..", "..", "..", "src", "makemore", "names.txt")
NW = int(sys.argv[1]) if len(sys.argv) > 1 else 300

with open(SRC) as f:
    lines = f.read().splitlines()[:NW]
text = "\n".join(lines) + "\n"
escaped = text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")

with open(os.path.join(HERE, "names_subset.viv"), "w") as f:
    f.write("###\n")
    f.write(f"The first {NW} lines of karpathy/makemore names.txt, as the raw text of the file.\n")
    f.write("Generated by gen_names.py; do not edit.\n")
    f.write("###\n\n")
    f.write("#| The contents of names.txt (a prefix), one name per line, as character codes.\n")
    f.write("def names_file() {\n")
    f.write(f'    return chars("{escaped}")\n')
    f.write("}\n")
print(f"wrote names_subset.viv: {NW} lines, {len(text)} characters")
