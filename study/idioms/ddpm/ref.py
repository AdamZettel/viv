"""Reference run for ddpm.viv, using the unmodified labml DDPM code.

Imports DenoiseDiffusion, TimeEmbedding and Swish from the labml clone at
viv-wt/src/ddpm (labmlai/annotated_deep_learning_paper_implementations
@ 33ab02281c2b928e6b32792909cc79cbdcfe1d6a). The eps model is the same small
MLP ddpm.viv builds. All randomness after weight init is Viv's rand() stream
(Park-Miller MINSTD) replayed here, fed to labml through torch.randint and
torch.randn, so both programs see the same batches and the same sampling noise.

Writes ddpm_ref.viv (weights in, reference values out) and prints the same
summary lines ddpm.viv prints.
"""
import math
import os
import sys

import torch
from torch import nn

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "..", "src", "ddpm"))
from labml_nn.diffusion.ddpm import DenoiseDiffusion  # noqa: E402
from labml_nn.diffusion.ddpm.unet import TimeEmbedding, Swish  # noqa: E402

torch.set_default_dtype(torch.float64)

T, TIME_CH, HIDDEN, BATCH = 1000, 32, 32, 128
TRAIN_STEPS, LR, NSAMPLE, REPORT = 3000, 1.0e-3, 512, 500


class Rng:
    """Viv's srand/rand: Park-Miller MINSTD, exact in integers."""

    def __init__(self, seed):
        self.state = int(abs(seed)) % 2147483646 + 1

    def rand(self):
        self.state = (16807 * self.state) % 2147483647
        return self.state / 2147483647.0

    def randn(self):
        u1 = self.rand()
        u2 = self.rand()
        return math.sqrt(-2.0 * math.log(u1)) * math.cos(2.0 * 3.141592653589793 * u2)

    def randn_matrix(self, rows, cols):
        return torch.tensor([[self.randn() for _ in range(cols)] for _ in range(rows)])

    def roll_batch(self, n):
        pts = []
        for _ in range(n):
            s = 1.5 * 3.141592653589793 * (1.0 + 2.0 * self.rand())
            pts.append([s * math.cos(s) / 7.0, s * math.sin(s) / 7.0])
        return torch.tensor(pts)

    def draw_steps(self, n):
        return torch.tensor([math.floor(self.rand() * T) for _ in range(n)], dtype=torch.long)


class EpsMLP(nn.Module):
    """x (B,2,1,1), t (B,) -> predicted noise (B,2,1,1)."""

    def __init__(self):
        super().__init__()
        self.time_emb = TimeEmbedding(TIME_CH)
        self.inp = nn.Linear(2, HIDDEN)
        self.hid = nn.Linear(HIDDEN, HIDDEN)
        self.out = nn.Linear(HIDDEN, 2)
        self.act = Swish()

    def forward(self, x, t):
        h = self.act(self.inp(x.reshape(-1, 2)) + self.time_emb(t))
        h = self.act(self.hid(h))
        return self.out(h).reshape(-1, 2, 1, 1)

    def layers(self):
        te = self.time_emb
        return [te.lin1, te.lin2, self.inp, self.hid, self.out]


def flat(model, what):
    parts = []
    for lin in model.layers():
        w, b = (lin.weight, lin.bias) if what == "data" else (lin.weight.grad, lin.bias.grad)
        parts += [w.detach().t().reshape(-1), b.detach().reshape(-1)]
    return torch.cat(parts)


class Patched:
    """Hand labml's loss/p_sample the draws Viv made."""

    def __init__(self, randint=None, randn=None):
        self.ri, self.rn = randint, randn

    def __enter__(self):
        self.saved = torch.randint, torch.randn
        if self.ri is not None:
            torch.randint = lambda *a, **k: self.ri
        if self.rn is not None:
            torch.randn = lambda *a, **k: self.rn

    def __exit__(self, *exc):
        torch.randint, torch.randn = self.saved


def viv_array(name, x):
    x = x.detach().reshape(-1).tolist() if torch.is_tensor(x) else list(x)
    return f"{name} = [" + ", ".join(repr(float(v)) for v in x) + "]\n"


def viv_matrix(name, m):
    rows = ["[" + ", ".join(repr(float(v)) for v in r) + "]" for r in m.detach().tolist()]
    return f"{name} = [" + ",\n    ".join(rows) + "]\n"


def distance_to_roll(P, curve):
    return torch.cdist(P, curve).min(dim=1).values


def main():
    torch.manual_seed(0)
    model = EpsMLP()
    diffusion = DenoiseDiffusion(model, T, torch.device("cpu"))
    theta0 = flat(model, "data").clone()
    out = ["# GENERATED by ref.py -- do not edit\n"]
    out.append(viv_array("THETA0", theta0))
    out.append(viv_array("REF_BETA", diffusion.beta))
    out.append(viv_array("REF_ALPHA_BAR", diffusion.alpha_bar))
    print(f"alpha_bar[0]: {diffusion.alpha_bar[0].item():.6g}")
    print(f"alpha_bar[T - 1]: {diffusion.alpha_bar[T - 1].item():.6g}")

    rng = Rng(2020.0)
    opt = torch.optim.Adam(model.parameters(), lr=LR)
    losses = [0.0] * (TRAIN_STEPS // REPORT)
    for step in range(TRAIN_STEPS):
        x0 = rng.roll_batch(BATCH)
        t = rng.draw_steps(BATCH)
        eps = rng.randn_matrix(BATCH, 2)
        opt.zero_grad()
        with Patched(randint=t):
            loss = diffusion.loss(x0.reshape(-1, 2, 1, 1), noise=eps.reshape(-1, 2, 1, 1))
        loss.backward()
        if step == 0:
            with torch.no_grad():
                xt = diffusion.q_sample(x0.reshape(-1, 2, 1, 1), t, eps=eps.reshape(-1, 2, 1, 1))
                out.append(viv_matrix("REF_EPS_THETA0", model(xt, t).reshape(-1, 2)))
            out.append(f"REF_LOSS0 = {loss.item()!r}\n")
            out.append(viv_array("REF_GRAD0", flat(model, "grad")))
            print(f"loss0: {loss.item():.6g}")
        opt.step()
        if step == 0:
            out.append(viv_array("REF_THETA1", flat(model, "data")))
        losses[step // REPORT] += loss.item() / REPORT
    out.append(viv_array("REF_LOSSES", losses))
    out.append(viv_array("REF_THETA_FINAL", flat(model, "data")))
    for k, l in enumerate(losses):
        print(f"steps {k * REPORT}-{(k + 1) * REPORT - 1}: mean loss {l:.6g}")

    with torch.no_grad():
        x = rng.randn_matrix(NSAMPLE, 2).reshape(-1, 2, 1, 1)
        for k in range(T):
            step = T - k - 1
            z = rng.randn_matrix(NSAMPLE, 2).reshape(-1, 2, 1, 1)
            with Patched(randn=z):
                x = diffusion.p_sample(x, x.new_full((NSAMPLE,), step, dtype=torch.long))
    samples = x.reshape(-1, 2)
    target = rng.roll_batch(NSAMPLE)
    noise = rng.randn_matrix(NSAMPLE, 2)
    out.append(viv_matrix("REF_SAMPLES", samples))

    u = torch.arange(2000) / 1999.0
    s = 1.5 * 3.141592653589793 * (1.0 + 2.0 * u)
    curve = torch.stack([s * torch.cos(s) / 7.0, s * torch.sin(s) / 7.0], dim=1)
    for name, P in [("samples", samples), ("target", target), ("noise", noise)]:
        d = distance_to_roll(P, curve)
        print(f"{name}: mean ({P[:, 0].mean().item():.6g}, {P[:, 1].mean().item():.6g})"
              f" spread ({P[:, 0].std(unbiased=False).item():.6g}, {P[:, 1].std(unbiased=False).item():.6g})"
              f" distance to roll {d.mean().item():.6g}, within 0.1: {(d < 0.1).double().mean().item():.6g}")

    with open(os.path.join(HERE, "ddpm_ref.viv"), "w") as f:
        f.writelines(out)


if __name__ == "__main__":
    main()
