"""Emit GTH pseudopotential parameters as Viv source.

Viv has no file I/O and no strings-as-values, so a pseudopotential reaches a
program as array assignments. This script writes them, reading CP2K's
GTH_POTENTIALS table (the copy PySCF ships) so that NO parameter is ever typed
by hand -- a transcribed digit in an h_ij is a silent 50 meV error.

    python3 make_pseudo.py Si            -> Si GTH-PADE-q4, the default valence
    python3 make_pseudo.py Cu:q11 O      -> explicit valence for Cu, default for O

The arrays are indexed [species, ...] in the order given on the command line.
"""
import os, re, sys

# The table's layout, which the Viv arrays copy: a local part with up to NLOC
# coefficients C1..C4, and NL angular momentum channels l = 0..3 of up to
# NPMAX projectors each.
NLOC, NL, NPMAX = 4, 4, 3

def table_path():
    import pyscf
    return os.path.join(os.path.dirname(pyscf.__file__), 'pbc/gto/pseudo/gth-pade.dat')

def entries(path):
    out, cur = {}, None
    for line in open(path):
        if line.startswith('#') or not line.strip():
            continue
        t = line.split()
        if re.match(r'^[A-Z][a-z]?$', t[0]) and len(t) > 1 and t[1].startswith('GTH-'):
            cur = (t[0], t[1])
            out[cur] = []
        elif cur:
            out[cur].append(t)
    return out

def parse(rows):
    zion = sum(int(x) for x in rows[0])
    rloc, nexp = float(rows[1][0]), int(rows[1][1])
    c = [float(x) for x in rows[1][2:2 + nexp]] + [0.0] * (NLOC - nexp)
    nshell = int(rows[2][0])
    k, shells = 3, []
    for l in range(nshell):
        r, npr = float(rows[k][0]), int(rows[k][1])
        h = [[0.0] * NPMAX for _ in range(NPMAX)]
        vals = [float(x) for x in rows[k][2:]]
        k += 1
        for a in range(npr):
            if a > 0:
                vals = [float(x) for x in rows[k]]
                k += 1
            for b, v in enumerate(vals):
                h[a][a + b] = h[a + b][a] = v
        shells.append((r, npr, h))
    return zion, rloc, c, shells

def main(args):
    tab = entries(table_path())
    picks = []
    for a in args:
        el, _, q = a.partition(':')
        cands = sorted(k for k in tab if k[0] == el and (not q or k[1].endswith('-' + q)))
        if not cands:
            sys.exit(f"no GTH-PADE entry for {a}")
        # default valence: CP2K lists the recommended (largest-core-free) one first
        picks.append(cands[-1] if q else max(cands, key=lambda k: int(k[1].split('q')[-1])))
    ns = len(picks)
    print("# GTH/HGH pseudopotentials, LDA (Pade). GENERATED by dft/pseudo/make_pseudo.py")
    print("# from CP2K's GTH_POTENTIALS table -- do not edit by hand.")
    print("#   S. Goedecker, M. Teter, J. Hutter, PRB 54, 1703 (1996)")
    print("#   C. Hartwigsen, S. Goedecker, J. Hutter, PRB 58, 3641 (1998)")
    for s, k in enumerate(picks):
        print(f"#   species {s}: {k[0]} {k[1]}")
    print(f"NSPEC = {ns}.0")
    print(f"GTH_NLOC = {NLOC}.0         #: GTH_NLOC  coefficients C1..C{NLOC} of the local part")
    print(f"GTH_NL = {NL}.0           #: GTH_NL  angular momentum channels, l = 0 .. {NL - 1}")
    print(f"GTH_NPMAX = {NPMAX}.0        #: GTH_NPMAX  at most this many projectors in one channel")
    print("ZION = zeros(NSPEC)")
    print("RLOC = zeros(NSPEC)")
    print("CLOC = zeros(NSPEC, GTH_NLOC)")
    print("NPRJ = zeros(NSPEC, GTH_NL)       #: NPRJ  projectors per (species, l)")
    print("RPRJ = zeros(NSPEC, GTH_NL)       #: RPRJ  projector radius r_l per (species, l)")
    print("HPRJ = zeros(NSPEC, GTH_NL, GTH_NPMAX, GTH_NPMAX) #: HPRJ  the coupling matrix h^l_ij per (species, l)")
    for s, k in enumerate(picks):
        zion, rloc, c, shells = parse(tab[k])
        print(f"ZION[{s}] = {zion}.0")
        print(f"RLOC[{s}] = {rloc!r}")
        for i, v in enumerate(c):
            if v:
                print(f"CLOC[{s}, {i}] = {v!r}")
        for l, (r, npr, h) in enumerate(shells):
            print(f"NPRJ[{s}, {l}] = {npr}.0")
            print(f"RPRJ[{s}, {l}] = {r!r}")
            for a in range(npr):
                for b in range(npr):
                    if h[a][b]:
                        print(f"HPRJ[{s}, {l}, {a}, {b}] = {h[a][b]!r}")

if __name__ == '__main__':
    main(sys.argv[1:] or ['Si'])
