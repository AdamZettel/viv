"""Write the intent lens of lib/hf/mdg_kernels from `viv lens init --stdout`.

tools/cas/gen-integrals.sh runs this after the generator: every def of the
generated module gets an entry stamped with its current body hash, and the
words of each entry come from the def's family (mdg_r_<L>, mdg_e_<la><lb>,
mdg_pair_<la><lb>, mdg_gather_<L2>, and the three pickers). Reads the init output on stdin,
writes the .intent text on stdout.
"""
import re
import sys

MODULE = """module lib/hf/mdg_kernels
  The McMurchie-Davidson kernels that lib/cas writes: one def per
  angular-momentum class, straight-line Viv, generated by
  tools/cas/gen_integrals.viv and checked for staleness by
  `tools/cas/gen-integrals.sh --check`. The R defs compute the Hermite
  integrals of one primitive quartet, the E defs the expansion coefficients
  of one axis of a primitive pair, and the pair defs the Hermite expansion
  of every Cartesian component pair. lib/hf/mdg_eri builds the production
  ERIs and direct J and K on them; lib/hf/hermite holds the general loops
  they were generated from and the tests in lib/hf/mdg_eri hold the two
  together.
"""

R = """  why   Generated from `herm_rfill`'s recurrence with the loops and the cube
        offsets resolved, so a primitive quartet pays for the arithmetic
        only. Each sum has two terms and each product two factors, so the
        values are `herm_rfill`'s to the bit.
  S     the R cube, side `{D}`, offsets `(t {D} + u) {D} + v`
  al    the exponent `pq/(p + q)` of the primitive quartet
  X     the x component of `P - Q`
  Y     the y component of `P - Q`
  Z     the z component of `P - Q`
  F     the Boys values `F_0 .. F_{L}` at `al |P - Q|^2`
  pref  the factor of every entry, `2 pi^(5/2) / (p q sqrt(p + q))` for an ERI

  = r0    the top entry of each level, `(-2 al)^n pref F_n`; `q<n>_<t>_<u>_<v>` holds `R(n; t, u, v)`
  = S     level 0, written into the cube
"""

E = """  why   Generated from `herm_efill`'s recurrence (raise `i` with `j = 0`, then
        `j`); equal coefficients are one expression in the CAS's store and are
        computed once. The generator proved this recurrence equal to the
        direct expansion of `x_A^i x_B^j` in Hermite Gaussians before writing
        it.
  E     the table, `(i ({lb} + 1) + j) ({L} + 1) + t`
  a     the first primitive's exponent
  b     the second primitive's exponent
  X     the axis component of `A - B`

  = E     `E(0, 0, 0)`, the Gaussian product's prefactor on this axis
{more}"""

P = """  why   Generated so that the product of the three axes needs no zero test
        and no index arithmetic, and a prefix `E^x E^y` shared by several
        entries is multiplied once. lib/hf/mdg_eri moves the rows to
        spherical functions when the basis asks for them.
  V     the expansion, `[ncart_a ncart_b, nh]` flattened row-major; the caller zeroes it
  EX    scratch for the E table on x
  EY    scratch for the E table on y
  EZ    scratch for the E table on z
  a     the first primitive's exponent
  b     the second primitive's exponent
  X     the x component of `A - B`
  Y     the y component of `A - B`
  Z     the z component of `A - B`

  = mdg_e_{la}{lb}()  the E table of the x axis, then of y and z
  = V     the first entry of the expansion
"""

GATHER = """  why   Generated per ket order so the ket Hermite offsets and signs are
        constants and the bra offsets Int arithmetic: the general gather in
        lib/hf/mdg_eri reads both from a table and converts numbers to
        indices for every entry.
  BR    the matrix of signed Hermite values, `[np2 nh2, ncol]` flattened
  o     where this primitive quartet's columns start, row 0
  ncol  the columns of `BR`
  S     the R cube of the primitive quartet
  L1    the total order of the bra pair
  D     the side of the R cube

  = BR    the column of each bra Hermite function
"""

PICK = {
    "mdg_gather": """  why   One call site for the quartet loop; `-1` above the generated
        orders, where lib/hf/mdg_eri gathers from its offset tables.
  BR    the matrix of signed Hermite values
  o     where this primitive quartet's columns start
  ncol  the columns of `BR`
  S     the R cube
  L1    the total order of the bra pair
  D     the side of the R cube
  L2    the total order of the ket pair

  = mdg_gather_0()  one branch per order, each calling its order's def
""",
    "mdg_rfill": """  why   One call site for the quartet loop. It returns `-1` instead of
        stopping, because a def that stops cannot be called from a
        `parallel for`; the caller falls back to `herm_rfill`.
  S     the R cube
  L     the total angular momentum of the quartet
  al    the exponent `pq/(p + q)`
  X     the x component of `P - Q`
  Y     the y component of `P - Q`
  Z     the z component of `P - Q`
  F     the Boys values `F_0 .. F_L`
  pref  the factor of every entry

  = mdg_r_0()  one branch per class, each calling its class's def
""",
    "mdg_pair": """  why   One call site for the store; the caller falls back to the general
        loops of lib/hf/mdg_eri above the generated classes.
  V     the expansion, flattened row-major
  EX    scratch for the E table on x, `herm_esize(la, lb)`
  EY    scratch for the E table on y
  EZ    scratch for the E table on z
  la    the first shell's angular momentum
  lb    the second shell's angular momentum
  a     the first primitive's exponent
  b     the second primitive's exponent
  X     the x component of `A - B`
  Y     the y component of `A - B`
  Z     the z component of `A - B`

  = mdg_pair_00()  one branch per class, each calling its class's def
""",
}

out = [MODULE]
for line in sys.stdin:
    m = re.match(r"^(mdg_\w+)\s+@([0-9a-f]+)\s*$", line)
    if not m:
        continue
    name, h = m.groups()
    out.append(f"{name}  @{h}")
    r = re.match(r"mdg_r_(\d+)$", name)
    e = re.match(r"mdg_e_(\d)(\d)$", name)
    p = re.match(r"mdg_pair_(\d)(\d)$", name)
    if r:
        L = int(r.group(1))
        out.append(R.format(L=L, D=L + 1))
    elif e:
        la, lb = int(e.group(1)), int(e.group(2))
        more = "  = E#2   the first raised entry; each later line raises one more\n" if la + lb > 0 else ""
        out.append(E.format(la=la, lb=lb, L=la + lb, more=more))
    elif p:
        out.append(P.format(la=p.group(1), lb=p.group(2)))
    elif re.match(r"mdg_gather_\d+$", name):
        out.append(GATHER)
    elif name in PICK:
        out.append(PICK[name])
    else:
        sys.exit(f"gen_intent: no words for {name}")
sys.stdout.write("\n".join(out))
