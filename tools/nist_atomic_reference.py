"""Harvest NIST SRD 141 into lib/nistref.viv.

    python3 tools/nist_atomic_reference.py

"Atomic Reference Data for Electronic Structure Calculations": total energies,
their decomposition, and every orbital eigenvalue for the ground configuration
of H through U, in four variants of the local density approximation. NIST's
stated target is one microHartree, and the values were cross-checked between
several independent codes and several machines.

This is the oracle for atomic density functional theory. It is what dftatom
validates against, which is why lib/radial is aimed at it.

    https://math.nist.gov/DFTdata/atomdata/tables/ptable.html

Fetched politely and cached under tools/.nistcache so a rerun costs nothing.
"""
import os
import re
import html
import time
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CACHE = os.path.join(os.path.dirname(os.path.abspath(__file__)), ".nistcache")
BASE = "https://math.nist.gov/DFTdata/atomdata/tables/"

# Light atoms first: the ones a radial code should get right before anything
# else, and the ones whose configurations are unambiguous.
ELEMENTS = [
    (1, "H"), (2, "He"), (3, "Li"), (4, "Be"), (5, "B"), (6, "C"),
    (7, "N"), (8, "O"), (9, "F"), (10, "Ne"), (11, "Na"), (12, "Mg"),
    (13, "Al"), (14, "Si"), (15, "P"), (16, "S"), (17, "Cl"), (18, "Ar"),
]
METHODS = ["LDA", "LSD", "RLDA", "ScRLDA"]


def fetch(z, sym):
    os.makedirs(CACHE, exist_ok=True)
    path = os.path.join(CACHE, "%02d%s.html" % (z, sym))
    if not os.path.exists(path):
        url = "%s%02d%s.html" % (BASE, z, sym)
        req = urllib.request.Request(url, headers={"User-Agent": "viv-lang reference harvester"})
        with urllib.request.urlopen(req, timeout=30) as r:
            open(path, "wb").write(r.read())
        time.sleep(0.5)
    return open(path, encoding="utf-8", errors="replace").read()


def strip(t):
    t = re.sub(r"<script.*?</script>", "", t, flags=re.S | re.I)
    t = re.sub(r"<[^>]+>", "\n", t)
    return [html.unescape(l).strip() for l in t.split("\n")]


def parse(z, sym):
    """The neutral atom's block: energies, then (label, [eigenvalues]) pairs."""
    lines = [l for l in strip(fetch(z, sym)) if l]
    # the neutral atom's header, then everything up to the cation's
    start = next(i for i, l in enumerate(lines) if re.match(r"^%d\s+%s\s" % (z, sym), l))
    stop = next((i for i, l in enumerate(lines[start + 1:], start + 1)
                 if re.match(r"^%d\s+%s\+" % (z, sym), l)), len(lines))
    block = lines[start:stop]
    config = block[0].split(None, 2)[2] if len(block[0].split(None, 2)) > 2 else ""
    energies, eigs = {}, []
    for line in block:
        m = re.match(r"^(Etot|Ekin|Ecoul|Eenuc|Exc)\s*=\s*(.*)$", line)
        if m:
            energies[m.group(1)] = [float(v) for v in m.group(2).split()]
            continue
        m = re.match(r"^(\d[spdf])\s+(-?\d.*)$", line)
        if m:
            eigs.append((m.group(1), [float(v) for v in m.group(2).split()]))
    return config, energies, eigs


out = [
    "###",
    "post: What NIST says an atom's energy is",
    "date: 2026-09-23",
    "",
    "Generated by `tools/nist_atomic_reference.py` from NIST Standard Reference",
    "Database 141, Atomic Reference Data for Electronic Structure Calculations:",
    "<https://math.nist.gov/DFTdata/atomdata/tables/ptable.html>",
    "",
    "Total energies, their decomposition into kinetic, Hartree, electron-nucleus",
    "and exchange-correlation parts, and the orbital eigenvalues, for the ground",
    "configuration of each atom. NIST's stated target is one microHartree, and",
    "the values were reproduced across several independent codes and machines --",
    "which is what makes this an oracle rather than another code's opinion.",
    "",
    "Only the first column, the plain local density approximation, is taken here.",
    "The relativistic variants are what a Dirac solver would be held to.",
    "",
    "Do not edit this file.",
    "###",
    "",
]
count = 0
for z, sym in ELEMENTS:
    config, en, eigs = parse(z, sym)
    if "Etot" not in en:
        print("  %s: no energies parsed" % sym)
        continue
    name = sym.lower()
    labels = [lab for lab, _ in eigs]
    lda = [vals[0] for _, vals in eigs]
    out += [
        "# ---- %s (Z = %d), %s ----" % (sym, z, config),
        "%s_Z = %d" % (name.upper(), z),
        "%s_LDA_ETOT = %r" % (name.upper(), en["Etot"][0]),
        "%s_LDA_EKIN = %r" % (name.upper(), en["Ekin"][0]),
        "%s_LDA_ECOUL = %r" % (name.upper(), en["Ecoul"][0]),
        "%s_LDA_EENUC = %r" % (name.upper(), en["Eenuc"][0]),
        "%s_LDA_EXC = %r" % (name.upper(), en["Exc"][0]),
        "#| The occupied orbital eigenvalues in LDA, in the order %s." % " ".join(labels),
        "def %s_lda_eigs() {" % name,
        "    return [%s]" % ", ".join(repr(v) for v in lda),
        "}",
        "",
    ]
    count += 1
    print("  %-3s Z=%-3d Etot(LDA) = %12.6f   %d eigenvalues" % (sym, z, en["Etot"][0], len(lda)))

out += [
    'test "the NIST energies add up the way NIST says they do" {',
    "    # Etot = Ekin + Ecoul + Eenuc + Exc, exactly, for every atom taken",
]
for z, sym in ELEMENTS[:count]:
    n = sym.upper()
    out += [
        "    assert_near(%s_LDA_ETOT, %s_LDA_EKIN + %s_LDA_ECOUL + %s_LDA_EENUC + %s_LDA_EXC, 2.0e-6)" % (n, n, n, n, n),
    ]
out += ["}", ""]

out += [
    'test "the atoms are bound, their shells are ordered, and heavier is deeper" {',
    "    # Every occupied level is below zero and they rise with n and l, which",
    "    # is the shell structure the table is a table of.",
]
for z, sym in ELEMENTS[:count]:
    n = sym.upper()
    out += [
        "    e_%s = %s_lda_eigs()" % (sym.lower(), sym.lower()),
        "    for i to len(e_%s) {" % sym.lower(),
        "        assert_lt(e_%s[i], 0.0)" % sym.lower(),
        "    }",
        "    for i to len(e_%s) - 1 {" % sym.lower(),
        "        assert_lt(e_%s[i], e_%s[i + 1])" % (sym.lower(), sym.lower()),
        "    }",
    ]
out += ["    # and the total energy falls as the nucleus grows"]
for a, b in zip(ELEMENTS[:count], ELEMENTS[1:count]):
    out += ["    assert_lt(%s_LDA_ETOT, %s_LDA_ETOT)" % (b[1].upper(), a[1].upper())]
out += ["}", ""]

out += [
    'test "the virial theorem does NOT hold for these, and that is the point" {',
    "    # For the exact solution of a Coulomb Hamiltonian, 2T + V = 0, so the",
    "    # kinetic energy would be minus the total. It is not, and asserting that",
    "    # it was is how this test started. Ekin here is the NON-interacting",
    "    # Kohn-Sham kinetic energy, which is not the interacting one, and the",
    "    # Levy-Perdew relation that does hold in density functional theory",
    "    # carries a scaling term in the exchange-correlation energy.",
    "    #",
    "    # NIST's own numbers say so: for oxygen T is 74.116881 against -Etot of",
    "    # 74.473077, half a percent apart. Left here as an assertion of the gap",
    "    # rather than deleted, so nobody puts it back.",
]
for z, sym in ELEMENTS[:count]:
    n = sym.upper()
    out += ["    assert_lt(1.0e-4, abs(%s_LDA_EKIN + %s_LDA_ETOT) / abs(%s_LDA_ETOT))" % (n, n, n)]
out += ["}", ""]

open(os.path.join(ROOT, "lib", "nistref.viv"), "w").write("\n".join(out) + "\n")
print("wrote lib/nistref.viv (%d elements)" % count)
