// Glyph metrics of the KaTeX fonts, for the mathtext of figure labels
// (lang/viv/src/mathtext.rs and www/src/lib/mathtext.js lay out `$...$` with
// them). Reads KaTeX's own table (katex/src/fontMetricsData.js, MIT) and
// writes it as Rust and as JavaScript, so both renderers measure alike.
//
//   node tools/mathtext/gen_metrics.mjs          # rewrite both files
//   node tools/mathtext/gen_metrics.mjs --check  # exit 1 if either is stale
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const src = join(root, 'www', 'node_modules', 'katex', 'src', 'fontMetricsData.js');
const data = (await import(pathToFileURL(src).href)).default;
const version = JSON.parse(readFileSync(join(root, 'www', 'node_modules', 'katex', 'package.json'), 'utf8')).version;

// the faces the labels use, in the order of the Font enum
const FONTS = ['Main-Regular', 'Main-Bold', 'Main-Italic', 'Math-Italic', 'Math-BoldItalic', 'Size1-Regular'];
const head = (c) => `${c} SPDX-License-Identifier: MIT
${c} SPDX-FileCopyrightText: 2013-2024 Khan Academy and other contributors (KaTeX)
${c} GENERATED by tools/mathtext/gen_metrics.mjs from KaTeX ${version}
${c} (src/fontMetricsData.js); do not edit. Per glyph, in em:
${c} [depth, height, italic correction, skew, width].
`;
const rows = (f) => Object.entries(data[f]).map(([k, v]) => [Number(k), v]).sort((a, b) => a[0] - b[0]);
const n = (x) => (Number.isInteger(x) ? x.toFixed(1) : String(x));

let rs = head('//') + '\n';
rs += `pub const FONTS: [&[(u32, [f64; 5])]; ${FONTS.length}] = [${FONTS.map((f) => f.replace('-', '_').toUpperCase()).join(', ')}];\n`;
const jsParts = [];
for (const f of FONTS) {
  const name = f.replace('-', '_').toUpperCase();
  rs += `\npub const ${name}: &[(u32, [f64; 5])] = &[\n`;
  for (const [k, v] of rows(f)) rs += `    (${k}, [${v.map(n).join(', ')}]),\n`;
  rs += '];\n';
  jsParts.push(`const ${name} = new Map([\n${rows(f).map(([k, v]) => `  [${k}, [${v.join(', ')}]],`).join('\n')}\n]);\n`);
}
const js = head('//') + '\n' + jsParts.join('\n') + `\nexport const FONTS = [${FONTS.map((f) => f.replace('-', '_').toUpperCase()).join(', ')}];\n`;

const out = [[join(root, 'lang', 'viv', 'src', 'mathtext_metrics.rs'), rs], [join(root, 'www', 'src', 'lib', 'mathtextMetrics.js'), js]];
if (process.argv.includes('--check')) {
  let stale = 0;
  for (const [p, t] of out) {
    let have = '';
    try { have = readFileSync(p, 'utf8'); } catch {}
    if (have !== t) { console.error(`stale: ${p}`); stale++; }
  }
  process.exit(stale ? 1 : 0);
}
for (const [p, t] of out) writeFileSync(p, t);
console.log('wrote', out.map((o) => o[0].slice(root.length + 1)).join(', '));
