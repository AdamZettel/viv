// Build lib/corpus.viv: the training text for the speedrun, as Viv source.
//
//     node tools/make_corpus.mjs
//
// The corpus is this repository's own numerical library. A character model
// trained on it has to learn Viv's syntax -- where braces close, that `def`
// takes a name and parentheses, that a comment runs to the end of a line -- so
// what it generates can be read and judged by anyone who has seen the language.
//
// It is emitted as `chars("...")`, which the parser turns into an array of
// character codes. Nothing in the pipeline handles text; the corpus is numbers
// from the moment it is parsed.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
// A fixed list, so the corpus does not change when a module is added, and
// never including the generated file itself.
const SOURCES = ['schur.viv', 'are.viv', 'lyap.viv', 'svd.viv', 'chain.viv', 'nn.viv', 'polar.viv'];
const LIMIT = 32768;

let text = SOURCES.map((f) => readFileSync(join(ROOT, 'lib', f), 'utf8')).join('\n');
// drop the fenced headers: prose about the code is not the code
text = text.replace(/^###[\s\S]*?^###$/gm, '').replace(/\n{3,}/g, '\n\n').trimStart();
text = text.slice(0, LIMIT);

const vocab = [...new Set(text)].sort();
const escaped = text
  .replace(/\\/g, '\\\\')
  .replace(/"/g, '\\"')
  .replace(/\n/g, '\\n')
  .replace(/\t/g, '\\t');

const out = `###
post: The speedrun's training text
date: 2026-09-23

Generated by \`tools/make_corpus.mjs\`. ${text.length} characters of this
repository's own numerical library -- ${SOURCES.join(', ')} -- with the prose
headers removed, so what is left is ${vocab.length} distinct characters of Viv
source and nothing else.

A character model trained on it has to learn where a brace closes, that \`def\`
is followed by a name and a parenthesis, and that a \`#\` runs to the end of the
line. Those are things a reader can check by looking, which is the point of
training on a language rather than on prose.

Edit \`tools/make_corpus.mjs\` and run it again; do not edit this file.
###

CORPUS_N = ${text.length}
CORPUS_VOCAB = ${vocab.length}

#| The training text, as character codes.
def corpus() {
    return chars("${escaped}")
}

#| The distinct characters, ascending, so that a code can be turned into a token
#| index and back.
def corpus_vocab() {
    return chars("${vocab.join('').replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n').replace(/\t/g, '\\t')}")
}

test "the corpus is the size and the alphabet the header claims" {
    c = corpus()
    v = corpus_vocab()
    assert_near(len(c), CORPUS_N, 1.0e-12)
    assert_near(len(v), CORPUS_VOCAB, 1.0e-12)
    # the alphabet ascends and has no repeats
    for i to CORPUS_VOCAB - 1 {
        assert_lt(v[i], v[i + 1])
    }
    # and every character of the corpus is in it
    for i to CORPUS_N {
        lo = 0
        hi = CORPUS_VOCAB - 1
        while lo < hi {
            mid = floor((lo + hi) / 2.0)
            if v[mid] < c[i] {
                lo = mid + 1
            }
            else {
                hi = mid
            }
        }
        assert_near(v[lo], c[i], 1.0e-12)
    }
}
`;
writeFileSync(join(ROOT, 'lib', 'corpus.viv'), out);
console.log(`lib/corpus.viv: ${text.length} characters, ${vocab.length} distinct`);
