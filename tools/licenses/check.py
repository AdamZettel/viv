"""Check the repository's licensing against the REUSE rules (reuse.software,
spec 3.x) that Viv needs, without the `reuse` tool.

    python3 tools/licenses/check.py            # exit 1 on any problem
    python3 tools/licenses/check.py --list     # each tracked file, its license

The rules:

1. Every tracked file has a license and a copyright notice: in a comment in
   the file (`SPDX-License-Identifier:`, `SPDX-FileCopyrightText:`), in a
   `<file>.license` beside it, or from an annotation of REUSE.toml.
2. Every license named is a known SPDX id or a `LicenseRef-`, and has its
   text in LICENSES/<id>.txt; every text in LICENSES/ is used.
3. Viv's policy on top of REUSE: a hand-written source file whose language
   has comments carries the header itself (REUSE.toml is for data, generated
   files and vendored code), and nothing is under the GPL or AGPL.

LICENSING.md explains the scheme.
"""
from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

KNOWN = {
    "MIT", "Apache-2.0", "MPL-2.0", "BSD-2-Clause", "BSD-3-Clause", "ISC", "Zlib",
    "OFL-1.1", "blessing", "SunPro", "CC0-1.0", "CC-BY-4.0", "Unlicense", "BSL-1.0",
    "PSF-2.0", "Python-2.0", "LGPL-2.1-only", "LGPL-2.1-or-later", "LGPL-3.0-only",
    "LGPL-3.0-or-later", "GPL-2.0-only", "GPL-2.0-or-later", "GPL-3.0-only",
    "GPL-3.0-or-later", "AGPL-3.0-only", "AGPL-3.0-or-later", "LLVM-exception",
}
OPERATORS = {"AND", "OR", "WITH"}

# Languages with comments: their hand-written files carry the header.
COMMENTED = {
    ".rs", ".py", ".viv", ".vivh", ".c", ".h", ".cpp", ".js", ".mjs", ".cjs", ".jsx",
    ".ts", ".tsx", ".astro", ".css", ".sh", ".toml", ".yml", ".yaml", ".jl", ".sql",
    ".f", ".f90", ".pl",
}
# A file that says it is generated is covered by REUSE.toml instead.
GENERATED = re.compile(r"do not edit|@generated|Generated by|generated by `?[\w./ -]+`?;? (?:edit|do)"
                       r"|^\W*[\w.]+: generated from \S+ \(|Generated from `|Written by `", re.I | re.M)
# Hand-written files whose header lives in REUSE.toml: a test prints the
# whole program and compares it with a recorded output.
HEADER_IN_TOML = {"lang/viv/features/examples/view-lenses.viv"}
# Files the REUSE tool itself leaves alone.
IGNORED = re.compile(r"^(LICENSES/.*|LICENSE(-[A-Z]+)?|COPYING.*|.*\.license|.*/LICENSE(\.\w+)?|.*/LICENSE-[\w.-]+|.*/COPYING.*)$")

TAG_LICENSE = re.compile(r"SPDX-License-Identifier:\s*([^\\\n]+)")
TAG_COPY = re.compile(r"(?:SPDX-FileCopyrightText:|SPDX-SnippetCopyrightText:)\s*(.+)")
CLOSERS = re.compile(r"\s*(\*/|-->|\"|'|\)|;|,)*\s*$")


def tracked() -> list[str]:
    out = subprocess.run(["git", "-C", str(ROOT), "ls-files", "-z"], capture_output=True, check=True).stdout
    return [p for p in out.decode().split("\0") if p and (ROOT / p).is_file()]


def glob_re(pattern: str) -> re.Pattern:
    """REUSE.toml's globs: `*` within a directory, `**` across them."""
    out, i = "", 0
    while i < len(pattern):
        if pattern.startswith("\\*", i):
            out, i = out + re.escape("*"), i + 2
        elif pattern.startswith("**", i):
            out, i = out + ".*", i + 2
        elif pattern[i] == "*":
            out, i = out + "[^/]*", i + 1
        else:
            out, i = out + re.escape(pattern[i]), i + 1
    return re.compile(out + r"\Z")


def load_toml(path: Path) -> dict:
    try:
        import tomllib
    except ImportError:
        import tomli as tomllib
    return tomllib.loads(path.read_text(encoding="utf-8"))


def annotations() -> list[dict]:
    data = load_toml(ROOT / "REUSE.toml")
    if data.get("version") != 1:
        raise SystemExit("REUSE.toml: version = 1 is the only version this checker reads")
    out = []
    for a in data.get("annotations", []):
        paths = a["path"] if isinstance(a["path"], list) else [a["path"]]
        lic = a.get("SPDX-License-Identifier")
        cop = a.get("SPDX-FileCopyrightText")
        out.append({
            "paths": [glob_re(p) for p in paths],
            "precedence": a.get("precedence", "closest"),
            "license": [lic] if isinstance(lic, str) else list(lic or []),
            "copyright": [cop] if isinstance(cop, str) else list(cop or []),
        })
    return out


def toml_info(path: str, anns: list[dict]):
    """The last annotation of REUSE.toml that matches `path` (later ones win)."""
    hit = None
    for a in anns:
        if any(r.match(path) for r in a["paths"]):
            hit = a
    return hit


def header_info(text: str):
    """The SPDX tags in a file's text, outside REUSE-IgnoreStart/End."""
    text = re.sub(r"REUSE-IgnoreStart.*?(REUSE-IgnoreEnd|\Z)", "", text, flags=re.S)
    lic = [CLOSERS.sub("", m.group(1)).strip() for m in TAG_LICENSE.finditer(text)]
    cop = [CLOSERS.sub("", m.group(1)).strip() for m in TAG_COPY.finditer(text)]
    return [l for l in lic if l], [c for c in cop if c]


def read_text(path: Path):
    data = path.read_bytes()
    if b"\0" in data[:8192]:
        return None
    return data.decode("utf-8", errors="replace")


def license_ids(expr: str) -> list[str]:
    toks = re.findall(r"[()]|[^\s()]+", expr)
    return [t for t in toks if t not in OPERATORS and t not in "()" and t != "+"]


def is_copyleft_strong(lid: str) -> bool:
    return lid.startswith(("GPL-", "AGPL-"))


def resolve(path: str, anns: list[dict]):
    """(licenses, copyrights, where, in_file) for one tracked file."""
    hit = toml_info(path, anns)
    if hit and hit["precedence"] == "override":
        return hit["license"], hit["copyright"], "REUSE.toml", False
    lic, cop, where = [], [], ""
    side = ROOT / (path + ".license")
    if side.is_file():
        lic, cop = header_info(side.read_text(encoding="utf-8"))
        where = path + ".license"
    else:
        # JSON holds no comments: a tag inside it is data (a program's text)
        text = None if path.endswith(".json") else read_text(ROOT / path)
        if text is not None:
            lic, cop = header_info(text)
            where = "header"
    in_file = bool(lic)
    if hit and hit["precedence"] == "aggregate":
        lic, cop = lic + [l for l in hit["license"] if l not in lic], cop + [c for c in hit["copyright"] if c not in cop]
        where = where + "+REUSE.toml" if in_file else "REUSE.toml"
    elif hit:
        if not lic:
            lic, where = hit["license"], (where + "+REUSE.toml") if cop else "REUSE.toml"
        if not cop:
            cop = hit["copyright"]
    return lic, cop, where, in_file


def main(argv) -> int:
    anns = annotations()
    texts = {p.stem: p for p in (ROOT / "LICENSES").glob("*") if p.is_file()}
    problems, used, listing = [], set(), []
    counts = {"header": 0, "toml": 0}
    for path in tracked():
        if IGNORED.match(path):
            continue
        lic, cop, where, in_file = resolve(path, anns)
        listing.append("%s\t%s\t%s" % (path, " AND ".join("(%s)" % l if " " in l and len(lic) > 1 else l for l in lic), where))
        counts["header" if in_file else "toml"] += 1
        if not lic:
            problems.append("%s: no license (add an SPDX header or a REUSE.toml annotation)" % path)
        if not cop:
            problems.append("%s: no copyright notice" % path)
        for expr in lic:
            for lid in license_ids(expr):
                used.add(lid)
                if lid not in KNOWN and not re.fullmatch(r"LicenseRef-[A-Za-z0-9.-]+", lid):
                    problems.append("%s: `%s` is not an SPDX license id this repository knows" % (path, lid))
                elif lid not in texts:
                    problems.append("%s: LICENSES/%s.txt is missing" % (path, lid))
                if is_copyleft_strong(lid):
                    problems.append("%s: %s; nothing in this repository may be under the GPL or AGPL" % (path, lid))
        suffix = Path(path).suffix
        if suffix in COMMENTED and not in_file and where != "REUSE.toml+override":
            hit = toml_info(path, anns)
            if hit and hit["precedence"] == "override":
                continue
            text = read_text(ROOT / path)
            head = "\n".join((text or "").splitlines()[:15])
            if text is not None and not GENERATED.search(head) and path not in HEADER_IN_TOML:
                problems.append("%s: no SPDX header; a hand-written source file carries one itself "
                                "(python3 tools/licenses/add_headers.py %s)" % (path, path))
    for lid in sorted(set(texts) - used):
        problems.append("LICENSES/%s: no file uses this license" % texts[lid].name)
    if "--list" in argv:
        print("\n".join(listing))
    for p in problems:
        print("licenses: " + p)
    print("licenses: %d files (%d with a header in the file, %d through REUSE.toml), %d licenses, %d problems"
          % (counts["header"] + counts["toml"], counts["header"], counts["toml"], len(texts), len(problems)))
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
