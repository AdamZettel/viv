def write_mix(row, translated):
    """A functional that libxc builds as a sum of others (xc_mix_init): the
    sum of the component modules' outputs, each with its own thresholds."""
    fam = "lda" if row["family"] in ("lda", "hyb_lda") else "gga"
    ids = [i for i, c in row["aux"]]
    if len(set(ids)) != len(ids):
        raise E.Unsupported("a component appears twice (libxc sets its parameters per copy)")
    comps = []
    for i, c in row["aux"]:
        if i not in translated:
            raise E.Unsupported(f"component {i} is not translated")
        comps.append((translated[i], c))
    lines = [MIX_HEADER.format(cfile=row["cfile"])]
    for k, ((cfam, cname), c) in enumerate(comps):
        lines.append(f"import xc.{cfam}.{cname} as c{k}")
    lines.append("")
    lines.append(f"#| {row['name'].upper()} (libxc id {row['id']}): {row['descr']}")
    lines.append("#|| " + " + ".join(f"{c!r} * {cname.upper()}" for (cfam, cname), c in comps))
    for r in row["refs"]:
        lines.append(f"#~ reference: {r}")
    if row["family"].startswith("hyb"):
        lines.append(f"#~ hybrid: exact-exchange fraction cam_alpha = {row['cam_alpha']!r}, cam_beta = "
                     f"{row['cam_beta']!r}, omega = {row['cam_omega']!r}; this module is the semilocal part only")
    for variant, nsp, nsg in (("unpol", 1, 1), ("pol", 2, 3)):
        args = "rho: Arr" if fam == "lda" else "rho: Arr, sigma: Arr"
        call = "rho" if fam == "lda" else "rho, sigma"
        width = 1 + nsp + (0 if fam == "lda" else nsg)
        lines.append("")
        lines.append(f"#| libxc's exc and vxc of the mixture, {'unpolarized' if variant == 'unpol' else 'spin-polarized'}: "
                     f"per point [zk, vrho{'' if fam == 'lda' else ', vsigma'}]")
        lines.append(f"def eval_{variant}({args}) -> Arr {{")
        lines.append(f"    nspin = {nsp}")
        lines.append(f"    width = {width}")
        lines.append(f"    n = len(rho) // nspin")
        lines.append(f"    out = zeros(width * n)")
        for k, ((cfam, cname), c) in enumerate(comps):
            if cfam == fam:
                lines.append(f"    out = out + {fmt_num(c)} * c{k}.eval_{variant}({call})")
            else:   # an LDA part of a GGA mixture: no vsigma columns
                cw = 1 + nsp
                lines.append(f"    part{k} = c{k}.eval_{variant}(rho)")
                lines.append(f"    for i to n {{")
                lines.append(f"        for j to {cw} {{")
                lines.append(f"            out[width * i + j] += {fmt_num(c)} * part{k}[{cw} * i + j]")
                lines.append(f"        }}")
                lines.append(f"    }}")
        lines.append("    return out")
        lines.append("}")
    return fam, "\n".join(lines) + "\n"


def fmt_num(x):
    s = repr(float(x))
    if "e" in s and "." not in s.split("e")[0]:
        m, ex = s.split("e")
        s = f"{m}.0e{ex}"
    return s


def write_module(row, libxc_src):
    fam, script, stype, defs, core_used, unused = translate(row, libxc_src)
    lines = [HEADER.format(script=f"maple/{stype}/{script}.mpl")]
    imports = sorted(core_used | ({"gga_unpol_point", "gga_pol_point"} if fam == "gga" else set()))
    if imports:
        lines.append(f"from xc.core import {', '.join(imports)}\n")
    ref = row["refs"][0] if row["refs"] else ""
    lines.append(f"#| {row['name'].upper()} (libxc id {row['id']}): {row['descr']}")
    lines.append(f"#|| kind {row['kind']}, family {row['family']}, Maple script {stype}/{script}.mpl")
    for r in row["refs"]:
        lines.append(f"#~ reference: {r}")
    if row["family"].startswith("hyb"):
        lines.append(f"#~ hybrid: exact-exchange fraction cam_alpha = {row['cam_alpha']!r}, cam_beta = "
                     f"{row['cam_beta']!r}, omega = {row['cam_omega']!r}; this module is the semilocal part only")
    dt = row["dens_threshold"]
    lines.append("")
    lines.append(f"#: DENS_THRESHOLD  libxc's dens_threshold for this functional: smaller total densities give zero")
    lines.append(f"DENS_THRESHOLD = {fmt_num(dt)}")
    if fam == "gga":
        lines.append("#: SIGMA_THRESHOLD  libxc's sigma_threshold, dens_threshold^(4/3)")
        lines.append(f"SIGMA_THRESHOLD = {fmt_num(dt ** (4.0 / 3.0))}")
    lines.append("")
    lines.append("\n\n".join(defs))
    lines.append(DRIVERS[fam])
    return fam, "\n".join(lines), dict(unused_params=unused, ref=ref)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("libxc_src")
    ap.add_argument("--only", default="")
    ap.add_argument("--out", default=os.path.join(ROOT, "xc"))
    a = ap.parse_args()
    rows = CAT.catalog(a.libxc_src)
    quarantine = json.load(open(os.path.join(HERE, "quarantine.json")))
    only = set(filter(None, a.only.split(",")))
    report = []
    for row in rows:
        if only and row["name"] not in only:
            continue
        entry = dict(id=row["id"], name=row["name"], family=row["family"], kind=row["kind"],
                     scripts=[f"{t}/{s}.mpl" for t, s in row["scripts"]], setter=row["setter"],
                     aux=row["aux"], cam_alpha=row["cam_alpha"], dens_threshold=row["dens_threshold"])
        if len(row["scripts"]) != 1:
            entry.update(status="skipped", reason="a mix of other functionals (no Maple script of its own)"
                         if row["aux"] else "no Maple script")
            report.append(entry)
            continue
        if row["name"] in quarantine:
            entry.update(status="skipped", reason="quarantined: " + quarantine[row["name"]])
            report.append(entry)
            continue
        if row["flags"] & (1 << 15):   # XC_FLAGS_VV10
            entry.update(status="skipped", reason="VV10 nonlocal correlation")
            report.append(entry)
            continue
        try:
            fam, text, info = write_module(row, a.libxc_src)
        except (E.Unsupported, RecursionError) as e:
            entry.update(status="skipped", reason=str(e)[:200])
            report.append(entry)
            continue
        d = os.path.join(a.out, fam)
        os.makedirs(d, exist_ok=True)
        path = os.path.join(d, row["name"] + ".viv")
        with open(path, "w") as fh:
            fh.write(text)
        entry.update(status="translated", path=os.path.relpath(path, a.out), **info)
        report.append(entry)
        print("ok  ", row["name"], file=sys.stderr)
    translated = {e["id"]: tuple(e["path"][:-4].split("/")) for e in report if e["status"] == "translated"}
    for entry in report:
        row = next(r for r in rows if r["id"] == entry["id"])
        if entry["status"] != "skipped" or not row["aux"] or row["scripts"]:
            continue
        if row["name"] in quarantine:
            entry["reason"] = "quarantined: " + quarantine[row["name"]]
            continue
        try:
            fam, text = write_mix(row, translated)
        except E.Unsupported as e:
            entry["reason"] = f"a mix of other functionals: {e}"
            continue
        d = os.path.join(a.out, "mix")
        os.makedirs(d, exist_ok=True)
        path = os.path.join(d, row["name"] + ".viv")
        with open(path, "w") as fh:
            fh.write(text)
        entry.update(status="translated", path=os.path.relpath(path, a.out), reason="", mix_family=fam)
    if not only:
        with open(os.path.join(a.out, "catalog.json"), "w") as fh:
            json.dump(report, fh, indent=1)
    from collections import Counter
    print(Counter(e["status"] for e in report))
    for e in report:
        if e["status"] == "skipped":
            print(f"skip {e['name']}: {e['reason']}")


if __name__ == "__main__":
    main()
