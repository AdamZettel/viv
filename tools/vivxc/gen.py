MAPLE_ARGS = {"lda": ["r0", "r1"], "gga": ["r0", "r1", "s0", "s1", "s2"]}
# which libxc input each Maple argument is, per variant
ARG_INPUT = {
    ("lda", "unpol"): {"r0": 0, "r1": 0},
    ("lda", "pol"): {"r0": 0, "r1": 1},
    ("gga", "unpol"): {"r0": 0, "r1": 0, "s0": 1, "s1": 1, "s2": 1},
    ("gga", "pol"): {"r0": 0, "r1": 1, "s0": 2, "s1": 3, "s2": 4},
}


def params_of(row):
    """The functional's params struct, as the Maple names params_a_<field> see it.

    libxc's set_ext_params_cpy* setters copy the external parameters, in order,
    into the struct (src/util.c, copy_params), so the struct's fields read off
    the defaults; a custom setter is assumed to do the same (the oracle checks).
    With no setter, the init function's literal assignments give the values."""
    out = {}
    fields = row.get("fields")
    vals = [v for nm, v in row["ext"]]
    n_cam = {"set_ext_params_cpy_omega": 1, "set_ext_params_cpy_exx": 1, "set_ext_params_cpy_cam": 3,
             "set_ext_params_cpy_camy": 3, "set_ext_params_cpy_cam_sr": 2, "set_ext_params_cpy_lc": 1}
    vals = vals[:len(vals) - n_cam.get(row["setter"], 0)]
    if fields and vals and len(vals) <= len(fields):
        for (f, k), v in zip(fields, vals):
            if k is None:
                out[f] = v
            elif isinstance(k, tuple):
                rows = out.setdefault(f, [])
                while len(rows) <= k[0]:
                    rows.append([])
                rows[k[0]].append(v)
            else:
                out.setdefault(f, []).append(v)
    lits = row.get("literals", {})
    for f, v in lits.items():
        out.setdefault(f, v)
    # a case block (values for this functional only) overrides a shared default
    return out


def consts_of(row):
    dt = row["dens_threshold"]
    return {"p_a_dens_threshold": dt, "p_a_zeta_threshold": DBL_EPSILON,
            "p_a_sigma_threshold": dt ** (4.0 / 3.0), "p_a_tau_threshold": 1e-20,
            "p_a_cam_omega": row["cam_omega"], "p_a_cam_alpha": row["cam_alpha"],
            "p_a_cam_beta": row["cam_beta"], "DBL_EPSILON": DBL_EPSILON}


def incdirs_of(libxc_src):
    mdir = os.path.join(libxc_src, "maple")
    return [mdir] + [os.path.join(mdir, d) for d in ("lda_exc", "lda_vxc", "gga_exc", "gga_vxc", "mgga_exc",
                                                     "mgga_vxc")]


def family_of(row):
    stype, script = row["scripts"][0]
    return ("lda" if stype.startswith("lda") else "gga"), stype, script


def graph(row, libxc_src, variant):
    """The energy per particle of one functional as an expression graph over
    the Maple arguments r0, r1 (, s0, s1, s2). Returns (root, env)."""
    fam, stype, script = family_of(row)
    if stype.endswith("_vxc"):
        raise E.Unsupported("potential-only script (libxc gives no energy density)")
    params = params_of(row)
    if any(v is None for v in params.values() if isinstance(v, list)):
        raise E.Unsupported("array parameter with gaps")
    E.reset()
    text = f'Polarization := "{variant}":\n$include <{script}.mpl>\n' + DRIVER[(fam, variant)]
    env = M.Env(M.load_text(text, incdirs_of(libxc_src)), params, consts_of(row))
    vars_ = [E.var(a) for a in MAPLE_ARGS[fam]]
    dens = env.apply(env.lookup("dens"), vars_[:2])
    if variant == "pol":
        z = env.apply(env.lookup("zeta"), vars_[:2])
        inv = E.binop("/", E.const(1), dens)
        E.set_zeta(z, E.binop("*", E.const(2), E.binop("*", vars_[0], inv)),
                   E.binop("*", E.const(2), E.binop("*", vars_[1], inv)))
    env.set_density(env.apply(env.lookup("r_ws"), [dens]), dens, vars_[0], vars_[1], variant == "pol")
    root = env.apply(env.lookup("mzk"), vars_)
    if not isinstance(root, E.Node) or root.op == "bool":
        raise E.Unsupported("the energy is not an expression")
    return root, env


def translate(row, libxc_src):
    """-> (family, script, script type, defs, core helpers used, unused params) or raises Unsupported."""
    fam, stype, script = family_of(row)
    params = params_of(row)
    defs = []
    used = set()
    core_used = set()
    for variant in ("unpol", "pol"):
        root, env = graph(row, libxc_src, variant)
        used |= env.used_params
        names = INPUTS[(fam, variant)]
        em = E.Emitter({a: names[i] for a, i in ARG_INPUT[(fam, variant)].items()})
        lines, result = em.body(root)
        core_used |= em.core_used
        head = [f"    {nm} = x[{i}]" for i, nm in enumerate(names)]
        doc = "#| the energy per particle, unpolarized: x = [" if variant == "unpol" else \
            "#| the energy per particle, spin-polarized: x = ["
        defs.append("\n".join([doc + ", ".join(names) + "]",
                               f"def zk_{variant}(x: Arr) -> Num {{"] + head + lines + [f"    return {result}", "}"]))
    unused = sorted(set(params) - used)
    return fam, script, stype, defs, core_used, unused


