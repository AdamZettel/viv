"""Write lang/viv/src/interp/unicode_tables.rs: the Unicode character data Viv's
string builtins need, read out of CPython itself so that `upper`, `lower`,
`isalpha`, `split()`, `strip()`, `float()` and `repr` agree with this CPython
character for character.

    python3 tools/strings/gen_unicode_tables.py        # rewrites the file
    python3 tools/strings/gen_unicode_tables.py --check  # exits 1 if it would change

Every table is taken from str methods applied to one character, except the two
properties Python does not expose, Cased and Case_Ignorable, which `lower()`'s
final-sigma rule reads. Those are recovered from the rule itself:

    'A' + c + 'Σ'   lowers to a final ς  iff  c is case-ignorable or cased
    'ΑΣ' + c        lowers to a final ς  iff  c is case-ignorable or not cased

so c is case-ignorable iff both hold, and a character that is not
case-ignorable is cased iff the first holds. (The rule only ever asks whether a
character that is NOT case-ignorable is cased, so that is all the table keeps.)
"""
import sys
import unicodedata

OUT = "lang/viv/src/interp/unicode_tables.rs"
MAXCP = 0x110000


def chars():
    for c in range(MAXCP):
        if 0xD800 <= c <= 0xDFFF:
            continue
        yield c


def ranges(pred):
    out = []
    lo = None
    prev = None
    for c in chars():
        if pred(chr(c)):
            if lo is not None and c == prev + 1:
                prev = c
                continue
            if lo is not None:
                out.append((lo, prev))
            lo = prev = c
    if lo is not None:
        out.append((lo, prev))
    return out


def fmt_ranges(name, doc, rs):
    body = ", ".join("(0x%X, 0x%X)" % r for r in rs)
    return "/// %s (%d ranges)\npub static %s: &[(u32, u32)] = &[%s];\n" % (doc, len(rs), name, body)


def mapping(name, doc, f):
    """(c, target, n): n == 1 maps c to the code point target; otherwise c maps
    to n code points starting at POOL[target]."""
    rows = []
    pool = []
    for c in chars():
        m = f(chr(c))
        if m == chr(c):
            continue
        cps = [ord(x) for x in m]
        if len(cps) == 1:
            rows.append((c, cps[0], 1))
        else:
            rows.append((c, len(pool), len(cps)))
            pool.extend(cps)
    body = ", ".join("(0x%X, 0x%X, %d)" % r for r in rows)
    pbody = ", ".join("0x%X" % p for p in pool)
    return (
        "/// %s (%d characters change)\npub static %s: &[(u32, u32, u8)] = &[%s];\n" % (doc, len(rows), name, body)
        + "/// The code points of %s's mappings to more than one character.\npub static %s_POOL: &[u32] = &[%s];\n" % (name, name, pbody)
    )


def decimal_runs():
    """Runs (lo, hi, zero): the digit value of c in [lo, hi] is c - zero."""
    out = []
    for c in chars():
        d = unicodedata.decimal(chr(c), None)
        if d is None:
            continue
        zero = c - d
        if out and out[-1][1] == c - 1 and out[-1][2] == zero:
            out[-1] = (out[-1][0], c, zero)
        else:
            out.append((c, c, zero))
    return out


def sigma_final_last(s):
    """s ends with a capital sigma: whether it lowers to the final form."""
    return s.lower()[-1] == "ς"


def sigma_final_second(s):
    """s is an alpha, a capital sigma, then more: whether the sigma lowers to
    the final form (the alpha lowers to one character, so it is second)."""
    return s.lower()[1] == "ς"


def main():
    ignorable = lambda ch: sigma_final_last("A" + ch + "Σ") and sigma_final_second("ΑΣ" + ch)
    cased = lambda ch: (not ignorable(ch)) and sigma_final_last("A" + ch + "Σ")
    # sanity: the probe agrees with what is known of a few characters
    assert ignorable("'") and ignorable("́") and not ignorable("a")
    assert cased("a") and cased("A") and not cased("1") and not cased(" ")
    dec = decimal_runs()
    parts = [
        "//! GENERATED by tools/strings/gen_unicode_tables.py from CPython %s\n" % sys.version.split()[0],
        "//! (Unicode %s). Do not edit: rerun the script.\n" % unicodedata.unidata_version,
        "//!\n//! Sorted, inclusive code point ranges; `interp::strings` reads them, and\n",
        "//! the C runtime's tables are printed from them (`strings::c_tables`).\n\n",
        "pub const PYTHON: &str = \"%s\";\n" % sys.version.split()[0],
        "pub const UNICODE: &str = \"%s\";\n\n" % unicodedata.unidata_version,
        fmt_ranges("SPACE", "`str.isspace` of one character: what `split()` and `strip()` take away", ranges(str.isspace)),
        fmt_ranges("ALPHA", "`str.isalpha` of one character", ranges(str.isalpha)),
        fmt_ranges("DIGIT", "`str.isdigit` of one character", ranges(str.isdigit)),
        fmt_ranges("NUMERIC", "`str.isnumeric` of one character", ranges(str.isnumeric)),
        fmt_ranges("UPPER", "one character's `str.isupper`: CPython's Py_UNICODE_ISUPPER", ranges(str.isupper)),
        fmt_ranges("LOWER", "one character's `str.islower`: CPython's Py_UNICODE_ISLOWER", ranges(str.islower)),
        fmt_ranges("TITLE", "titlecase letters (CPython's Py_UNICODE_ISTITLE)", ranges(lambda ch: ch.istitle() and not ch.isupper())),
        fmt_ranges("PRINTABLE", "`str.isprintable` of one character: what `repr` writes as itself", ranges(str.isprintable)),
        fmt_ranges("CASE_IGNORABLE", "Case_Ignorable, as `lower()`'s final-sigma rule reads it", ranges(ignorable)),
        fmt_ranges("CASED", "Cased, among the characters that are not case-ignorable", ranges(cased)),
        "/// (lo, hi, zero): Unicode decimal digits; the value of c is c - zero (%d runs)\n" % len(dec),
        "pub static DECIMAL: &[(u32, u32, u32)] = &[%s];\n" % ", ".join("(0x%X, 0x%X, 0x%X)" % r for r in dec),
        mapping("TO_UPPER", "`str.upper` of one character", str.upper),
        mapping("TO_LOWER", "`str.lower` of one character (U+03A3 is decided by the final-sigma rule)", str.lower),
    ]
    text = "".join(parts)
    if "--check" in sys.argv:
        old = open(OUT, encoding="utf-8").read()
        sys.exit(0 if old == text else 1)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote", OUT, len(text), "bytes")


if __name__ == "__main__":
    main()
