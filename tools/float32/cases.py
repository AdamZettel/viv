"""Write lang/viv/tests/float32/cases.viv and the output it must print,
cases.txt, from references that are not Viv.

    python3 tools/float32/cases.py

- + - * / sqrt, comparisons, float32(x) of a double, the text of a Float32:
  NumPy float32 (IEEE binary32 operations; repr(np.float32) for the text).
- exp, log, sin, cos, tanh: the float32 nearest the mpmath value at 200
  bits, ties to even (NumPy's own float32 functions are not correctly
  rounded, so they are not the reference).
- float16 rounding: NumPy's float32 -> float16 conversion.
- bfloat16 rounding: written here from the IEEE definition with exact
  rational arithmetic (NumPy has no bfloat16; no package is installed).
- sum of a [Float32]: numpy.sum of the float32 array.
- dot of two [Float32]: s = s + a[i]*b[i] in float32, i ascending.
- sum of an [Int8]: Python's integers.

Every input is written in the program as the exact decimal of its float32
value, so reading it is exact in every engine.
"""
import random
import struct
from fractions import Fraction
from pathlib import Path

import mpmath
import numpy as np

mpmath.mp.prec = 200
f32 = np.float32
ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "lang/viv/tests/float32"
rng = random.Random(20261014)


def from_bits(b):
    return struct.unpack("<f", struct.pack("<I", b))[0]


def lit(x):
    """x (a float32) as a Viv literal that reads back exactly."""
    x = float(x)
    s = repr(x)
    return f"({s})" if s.startswith("-") else s


def text(x):
    """fmt(x) of a Float32: NumPy's repr digits."""
    return repr(f32(x))


def nearest32(v):
    c = f32(float(v))
    best = None
    for cand in (np.nextafter(c, f32(-np.inf)), c, np.nextafter(c, f32(np.inf))):
        if not np.isfinite(cand):
            continue
        d = abs(mpmath.mpf(float(cand)) - v)
        key = (d, int(cand.view(np.uint32)) & 1)
        if best is None or key < best[0]:
            best = (key, cand)
    return best[1]


def bf16(x):
    """x (a finite float32) rounded to bfloat16, ties to even, by exact
    arithmetic: the two bfloat16 values around x are x with its low 16 bits
    cleared, and that plus one bfloat16 step."""
    b = int(f32(x).view(np.uint32))
    lo = b & 0xFFFF0000
    hi = lo + 0x10000
    xl, xh = from_bits(lo), from_bits(hi & 0xFFFFFFFF)
    if (hi & 0x7F800000) == 0x7F800000 and (hi & 0x7FFFFF) == 0:
        xh = float("inf") if xl > 0 else float("-inf")
    fx = Fraction(float(x))
    dl = abs(fx - Fraction(xl))
    dh = abs(Fraction(xh) - fx) if np.isfinite(xh) else None
    if dh is None:
        # the next step is 2^128: compare against the midpoint 2^128 - 2^119
        mid = Fraction(2) ** 128 - Fraction(2) ** 119
        return xh if abs(fx) >= mid and not (abs(fx) == mid and (lo >> 16) & 1 == 0) else xl
    if dl < dh or (dl == dh and (lo >> 16) & 1 == 0):
        return f32(xl)
    return f32(xh)


def rand32(lo_exp=-20, hi_exp=20):
    """A random float32 with a random sign and exponent in a range."""
    m = rng.random() + 1.0
    e = rng.randint(lo_exp, hi_exp)
    return f32(m * 2.0**e * rng.choice([1, -1]))


prog = ["# Generated by tools/float32/cases.py; do not edit.", ""]
want = []


def out(line_viv, expect):
    prog.append(line_viv)
    want.append(expect)


# arithmetic, sqrt, comparisons
for _ in range(120):
    a, b = rand32(), rand32()
    if rng.random() < 0.3:
        b = f32(a * f32(1 + 2.0 ** -rng.randint(1, 30)))
    s = f"a: Float32 = {lit(a)}\nb: Float32 = {lit(b)}"
    prog.append(s)
    out("print(fmt(a + b), fmt(a - b), fmt(a * b), fmt(a / b), a < b, a == b)",
        f"{text(a + b)} {text(a - b)} {text(a * b)} {text(a / b)} {str(bool(a < b)).lower()} {str(bool(a == b)).lower()}")
    out("print(fmt(sqrt(abs(a))), fmt(-a), fmt(min(a, b)), fmt(max(a, b)))",
        f"{text(np.sqrt(abs(a)))} {text(-a)} {text(b if b < a else a)} {text(b if b > a else a)}")

# literals beside a Float32, and float32(x) of a double
for _ in range(40):
    a = rand32()
    d = rng.uniform(-100, 100)
    prog.append(f"a: Float32 = {lit(a)}")
    out(f"print(fmt(a * 3 + 0.5), fmt(float32({d!r})))", f"{text(a * f32(3) + f32(0.5))} {text(f32(d))}")

# the text of a Float32 over the whole range
for _ in range(80):
    x = from_bits(rng.getrandbits(32) & 0x7FFFFFFF)
    if not np.isfinite(x):
        continue
    x = f32(x) * rng.choice([1, -1])
    out(f"print(fmt(float32({lit(x)})))", text(x))

# the functions: the correctly rounded float32
FUNCS = {"exp": (mpmath.exp, -100, 89), "log": (mpmath.log, 1e-30, 1e30), "sin": (mpmath.sin, -1e4, 1e4), "cos": (mpmath.cos, -1e4, 1e4), "tanh": (mpmath.tanh, -12, 12)}
for name, (fn, lo, hi) in FUNCS.items():
    xs = []
    for _ in range(60):
        if name == "log":
            x = f32(10 ** rng.uniform(np.log10(lo), np.log10(hi)))
        else:
            x = f32(rng.uniform(lo, hi))
        xs.append(x)
    for x in xs:
        out(f"print(fmt({name}(float32({lit(x)}))))", text(nearest32(fn(mpmath.mpf(float(x))))))

# the inputs where the double function rounded once is not correctly rounded
# (interp/f32s.rs, EXCEPTIONS), and the hard inputs around them
import re
for name, xb in re.findall(r'\("(\w+)", 0x([0-9a-f]{8}), 0x[0-9a-f]{8}\)', (ROOT / "lang/viv/src/interp/f32s.rs").read_text()):
    x = f32(from_bits(int(xb, 16)))
    fn = FUNCS[name][0]
    out(f"print(fmt({name}(float32({lit(x)}))))", text(nearest32(fn(mpmath.mpf(float(x))))))

# bfloat16 and float16 rounding
for _ in range(80):
    x = rand32(-30, 30)
    if rng.random() < 0.3:
        # a tie or a near-tie for bfloat16
        b = (int(x.view(np.uint32)) & 0xFFFF0000) | rng.choice([0x8000, 0x7FFF, 0x8001, 0x0])
        x = f32(from_bits(b))
    out(f"print(fmt(bfloat16(float32({lit(x)}))), fmt(float16(float32({lit(x)}))))", f"{text(bf16(x))} {text(f32(np.float16(x)))}")

# sum of a [Float32] in NumPy's order, at the sizes where its order changes
for n in [0, 1, 7, 8, 9, 15, 16, 17, 127, 128, 129, 1000, 8191, 8192, 8193, 20000, 70001]:
    i = np.arange(n, dtype=np.int64)
    v = (f32(1) * ((i * 7919) % 100003 - 50000).astype(np.float32)) / f32(997)
    prog.append(f"w = float32_zeros({n})")
    prog.append(f"for i to {n} {{\n    w[i] = float32((i * 7919) % 100003 - 50000) / 997\n}}")
    out("print(fmt(sum(w)))", text(np.sum(v)))
    if n:
        u = (((i * 104729) % 1009) - 504).astype(np.float32) / f32(31)
        prog.append(f"u = float32_zeros({n})")
        prog.append(f"for i to {n} {{\n    u[i] = float32((i * 104729) % 1009 - 504) / 31\n}}")
        s = f32(0)
        for p, q in zip(v, u):
            s = f32(s + f32(p * q))
        out("print(fmt(dot(w, u)))", text(s))
        h = np.array([bf16(x) for x in v], dtype=np.float32)
        prog.append("h = bfloat16(w)")
        out("print(fmt(sum(h)), fmt(h[0]))", f"{text(np.sum(h))} {text(h[0])}")

# integer storage: reads, checked stores, sums
xs = [rng.randint(-128, 127) for _ in range(200)]
prog.append("q = int8_zeros(" + str(len(xs)) + ")")
prog.append("vals: [Int] = [" + ", ".join(str(x) for x in xs) + "]")
prog.append("for i to len(vals) {\n    q[i] = vals[i]\n}")
out("print(sum(q), q[0], q[-1], len(q))", f"{sum(xs)} {xs[0]} {xs[-1]} {len(xs)}")
prog.append("z = int32(int64(q))")
out("print(sum(z), int64(z)[5])", f"{sum(xs)} {xs[5]}")

OUT.mkdir(parents=True, exist_ok=True)
# the program's license header, at the end as in every .viv (split so the
# license checker does not read it as this file's own)
SPDX = "SPDX-" + "License-Identifier"
prog += ["", f"# {SPDX}: MIT OR Apache-2.0", "# SPDX-" + "FileCopyrightText: 2026 The Viv authors"]
(OUT / "cases.viv").write_text("\n".join(prog) + "\n")
(OUT / "cases.txt").write_text("\n".join(want) + "\n")
print(f"wrote {len(want)} lines to {OUT / 'cases.viv'} and cases.txt")
