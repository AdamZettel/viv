"""Writes ports/dftatom/states.viv from upstream's src/states.f90.

    python3 ports/dftatom/tools/gen_states.py /path/to/dftatom/src/states.f90

The nonrelativistic ground configurations (NIST's, Kotochigova et al., Phys.
Rev. A 55, 191 (1997)) as upstream lists them, Z = 1 to 92, flattened into
three [Int] tables and the offset of each atom's first orbital.
"""
import re
import sys
import os

src = open(sys.argv[1]).read()
body = src.split("subroutine get_atomic_states_nonrel")[1].split("end subroutine")[0]
cases = re.findall(r"case \((\d+)\)(.*?)(?=case \(|case default)", body, re.S)
tab = {}
for z, txt in cases:
    def arr(name):
        m = re.search(name + r" = \(/(.*?)/\)", txt, re.S)
        return [int(x) for x in m.group(1).replace("&", "").split(",")]
    no, lo, fo = arr("no"), arr("lo"), arr("fo")
    assert len(no) == len(lo) == len(fo)
    assert sum(fo) == int(z), z
    tab[int(z)] = (no, lo, fo)
assert sorted(tab) == list(range(1, 93))

start, N, L, F = [0], [], [], []
for z in range(1, 93):
    no, lo, fo = tab[z]
    N += no
    L += lo
    F += fo
    start.append(len(N))


def wrap(name, xs):
    lines, line = [], name + ": [Int] = ["
    for i, x in enumerate(xs):
        piece = str(x) + (", " if i < len(xs) - 1 else "]")
        if len(line) + len(piece) > 88:
            lines.append(line.rstrip())
            line = "    "
        line += piece
    lines.append(line)
    return "\n".join(lines)


out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "states.viv")
with open(out, "w") as f:
    f.write("""# Derived from dftatom src/states.f90 (get_atomic_states_nonrel and
# get_atomic_states_rel), Copyright (c) 2006-2012 Ondrej Certik, Jiri Vackar,
# John Pask; MIT license, see ports/dftatom/LICENSE.
#
# Generated by ports/dftatom/tools/gen_states.py; do not edit by hand.
#
# The ground configurations are NIST's: S. Kotochigova, Z. H. Levine,
# E. L. Shirley, M. D. Stiles and C. W. Clark, Phys. Rev. A 55, 191 (1997).

#| The first orbital of atom Z is entry STATE_START[Z - 1] of the tables below;
#| its last is entry STATE_START[Z] - 1.
""")
    f.write(wrap("STATE_START", start) + "\n\n")
    f.write("#| The principal quantum number n of each orbital, atom after atom.\n")
    f.write(wrap("STATE_N", N) + "\n\n")
    f.write("#| The orbital angular momentum l of each orbital.\n")
    f.write(wrap("STATE_L", L) + "\n\n")
    f.write("#| The number of electrons in each orbital.\n")
    f.write(wrap("STATE_F", F) + "\n")
print("wrote", out, len(N), "orbitals")
