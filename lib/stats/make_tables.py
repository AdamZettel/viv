"""Write lib/stats/tables.viv: the constants lib/stats/special.viv's series
use, computed by mpmath at 60 digits and rounded once to double.

    python3 lib/stats/make_tables.py > lib/stats/tables.viv
"""
import mpmath as mp

mp.mp.dps = 60
ZETA_TERMS = 64
PSI_TERMS = 32


def num(x):
    return repr(float(x))


def array(name, xs):
    out = ["%s = [" % name]
    for x in xs:
        out.append("    %s," % num(x))
    out.append("]")
    return "\n".join(out)


x0 = mp.findroot(mp.digamma, 1.4616)
x0_hi = float(x0)
x0_lo = x0 - mp.mpf(x0_hi)
print(
    """###
post: The constants of lib/stats/special.viv's series
agent: claude

Generated by lib/stats/make_tables.py with mpmath 1.3 at 60 digits, each
rounded once to the nearest double.

- `ZETA_M1[k - 2]` is zeta(k) - 1 for k = 2 to %d: the coefficients of the
  Taylor series of log Gamma about 1 and 2.
- `PSI_ROOT_HI + PSI_ROOT_LO` is the positive zero of the digamma function
  to twice double precision, and `PSI_ROOT_TAYLOR[n - 1]` is
  psi^(n)(x0) / n!, the Taylor coefficients of psi about that zero.

Used with `from stats.tables import ...`.
###
"""
    % (ZETA_TERMS + 1)
)
print(array("ZETA_M1", [mp.zeta(k) - 1 for k in range(2, ZETA_TERMS + 2)]))
print()
print("PSI_ROOT_HI = %s" % num(x0_hi))
print("PSI_ROOT_LO = %s" % num(x0_lo))
print(
    array(
        "PSI_ROOT_TAYLOR",
        [
            mp.polygamma(n, x0) / mp.factorial(n)
            for n in range(1, PSI_TERMS + 1)
        ],
    )
)
print("EULER_GAMMA = %s" % num(mp.euler))
print("LN_SQRT_2PI = %s" % num(mp.log(mp.sqrt(2 * mp.pi))))
print("SQRT_PI = %s" % num(mp.sqrt(mp.pi)))
print("SQRT_2PI = %s" % num(mp.sqrt(2 * mp.pi)))
print("SQRT_2 = %s" % num(mp.sqrt(2)))
print()
