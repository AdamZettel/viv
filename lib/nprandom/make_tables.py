"""Write lib/nprandom/ziggurat_tables.viv from NumPy's own table file.

    python3 lib/nprandom/make_tables.py                  fetch the header at the pinned commit
    python3 lib/nprandom/make_tables.py --header PATH    read a local copy
    python3 lib/nprandom/make_tables.py --check          fail if the committed file differs

The tables are numpy/random/src/distributions/ziggurat_constants.h of NumPy v1.24.4
(commit 9315a9072b2636f75c831b4eca9f42a5f67ca2fb): `ki_double` (uint64, below 2^52, so exact
in a double), `wi_double` and `fi_double` (decimal doubles, which C and Python both round
to the nearest double), and `ziggurat_nor_r`, `ziggurat_nor_inv_r`. Each double is written
as Python's repr, the shortest decimal that reads back as the same double in every Viv
engine.
"""

import argparse
import os
import re
import sys
import urllib.request

COMMIT = "9315a9072b2636f75c831b4eca9f42a5f67ca2fb"
URL = "https://raw.githubusercontent.com/numpy/numpy/%s/numpy/random/src/distributions/ziggurat_constants.h" % COMMIT
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "ziggurat_tables.viv")
TABLE_LEN = 256


def c_array(text, name):
    m = re.search(r"static const \w+ %s\[\] = \{(.*?)\};" % name, text, re.S)
    if not m:
        sys.exit("make_tables.py: no table %s in the header" % name)
    return [t.strip() for t in m.group(1).split(",") if t.strip()]


def c_scalar(text, name):
    m = re.search(r"static const double %s =\s*([-+0-9.eE]+);" % name, text)
    if not m:
        sys.exit("make_tables.py: no constant %s in the header" % name)
    return float(m.group(1))


def viv_array(vals, per_line=4):
    rows = [", ".join(vals[i:i + per_line]) for i in range(0, len(vals), per_line)]
    return "[\n    " + ",\n    ".join(rows) + "\n]"


def render(text):
    ki = [int(t.rstrip("ULL").rstrip("UL"), 16) for t in c_array(text, "ki_double")]
    wi = [float(t) for t in c_array(text, "wi_double")]
    fi = [float(t) for t in c_array(text, "fi_double")]
    for name, t in (("ki_double", ki), ("wi_double", wi), ("fi_double", fi)):
        if len(t) != TABLE_LEN:
            sys.exit("make_tables.py: %s has %d entries, not %d" % (name, len(t), TABLE_LEN))
    if max(ki) >= 2 ** 53:
        sys.exit("make_tables.py: a ki_double entry is not exact in a double")
    r = c_scalar(text, "ziggurat_nor_r")
    inv_r = c_scalar(text, "ziggurat_nor_inv_r")
    return """###
post: The ziggurat tables of NumPy's normal draws
agent: claude

Generated by lib/nprandom/make_tables.py from numpy/random/src/distributions/
ziggurat_constants.h, NumPy v1.24.4 (commit %s). Do not edit;
rerun the script. `npr_zig_ki` is `ki_double` (uint64 values below 2^52),
`npr_zig_wi` is `wi_double`, `npr_zig_fi` is `fi_double`; each double is the
shortest decimal that reads back as the header's double.

Used by lib/nprandom/generator.
###

NPR_ZIG_R = %r
NPR_ZIG_INV_R = %r

npr_zig_ki = %s

npr_zig_wi = %s

npr_zig_fi = %s
""" % (COMMIT, r, inv_r, viv_array([str(v) for v in ki]), viv_array([repr(v) for v in wi], 3),
       viv_array([repr(v) for v in fi], 3))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--header")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    if a.header:
        text = open(a.header).read()
    else:
        text = urllib.request.urlopen(URL, timeout=60).read().decode()
    out = render(text)
    if a.check:
        if open(OUT).read() != out:
            sys.exit("make_tables.py: %s differs from the tables at %s" % (OUT, COMMIT))
        print("ziggurat_tables.viv: current")
        return
    with open(OUT, "w") as f:
        f.write(out)
    print("wrote", OUT)


if __name__ == "__main__":
    main()
