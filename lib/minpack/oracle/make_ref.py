"""Write lib/minpack/mgh_ref.viv from the Fortran oracle's trace.

    python3 lib/minpack/oracle/make_ref.py <trace.txt> > lib/minpack/mgh_ref.viv

trace.txt is what oracle/build.sh writes: for each case a C line, an S line
(the starting norm), one T line per trial step and an F line (the result).
Only the problems lib/minpack/mgh.viv ports are kept. Numbers are written with
Python's repr, the shortest decimal that reads back as the same double.
"""
import sys

PORTED = {4, 5, 6, 7, 8, 9, 10, 12, 13, 17, 18}
NX = 11  # the widest x among the ported problems (Osborne 2)
# T line: iter nfev delta_in par_lm pnorm fnorm1 actred prered ratio delta par
#         accepted fnorm gnorm lmpar_iterations x...
# hist row (lmder.viv's H_ columns): the same, without lmpar_iterations


def num(s):
    return float(s.replace('D', 'E'))


def fmt(v):
    r = repr(float(v))
    if 'e' in r or 'E' in r:
        mant, exp = r.split('e')
        if '.' not in mant:
            mant += '.0'
        r = mant + 'e' + exp
    elif '.' not in r and 'inf' not in r and 'nan' not in r:
        r += '.0'
    return r


cases = []
for line in open(sys.argv[1]):
    w = line.split()
    if w[0] == 'C':
        cases.append({'nprob': int(w[1]), 'n': int(w[2]), 'm': int(w[3]), 'factor': num(w[4]), 'rows': []})
    elif w[0] == 'S':
        cases[-1]['fnorm0'] = num(w[2])
    elif w[0] == 'T':
        c = cases[-1]
        v = [num(t) for t in w[1:]]
        row = v[0:14] + v[15:]
        row += [0.0] * (14 + NX - len(row))
        c['rows'].append(row)
    elif w[0] == 'F':
        c = cases[-1]
        c['info'], c['nfev'], c['njev'] = int(w[1]), int(w[2]), int(w[3])
        c['fnorm'] = num(w[4])
        c['x'] = [num(t) for t in w[5:]]

cases = [c for c in cases if c['nprob'] in PORTED]
out = []
out.append('###')
out.append('post: The Fortran oracle for the MINPACK test problems')
out.append('agent: claude')
out.append('')
out.append('Generated by lib/minpack/oracle/make_ref.py from the output of')
out.append('lib/minpack/oracle/build.sh: netlib lmder1 (gfortran, -O0 -ffp-contract=off)')
out.append('on the cases of the netlib test data ref/file22.dat for the problems')
out.append('lib/minpack/mgh.viv ports. Do not edit; rerun the generator.')
out.append('')
out.append('MGH_REF_CASES[k] = nprob, n, m, factor, info, nfev, njev, final norm,')
out.append('starting norm, first row of case k in MGH_REF_HIST, number of rows.')
out.append('MGH_REF_X[k] = the final x, padded with zeros to 11 entries.')
out.append('MGH_REF_HIST: one row per trial step, in the columns of lmder.viv\'s')
out.append('H_ constants, x padded with zeros to 11 entries.')
out.append('###')
out.append('')
out.append(f'MGH_REF_NCASES = {len(cases)}')
rows = []
first = 0
lines = []
for c in cases:
    lines.append('[' + ', '.join(fmt(v) for v in [c['nprob'], c['n'], c['m'], c['factor'], c['info'], c['nfev'],
                                                  c['njev'], c['fnorm'], c['fnorm0'], first, len(c['rows'])]) + ']')
    first += len(c['rows'])
    rows += c['rows']
out.append('MGH_REF_CASES = [' + ',\n                 '.join(lines) + ']')
xl = ['[' + ', '.join(fmt(v) for v in (c['x'] + [0.0] * (NX - len(c['x'])))) + ']' for c in cases]
out.append('MGH_REF_X = [' + ',\n             '.join(xl) + ']')
hl = ['[' + ', '.join(fmt(v) for v in r) + ']' for r in rows]
out.append('MGH_REF_HIST = [' + ',\n                '.join(hl) + ']')
print('\n'.join(out))
